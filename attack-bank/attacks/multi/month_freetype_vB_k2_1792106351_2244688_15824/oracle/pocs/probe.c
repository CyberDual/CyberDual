int
main( void )
{
  FT_Library  library;
  FT_Face     face;
  FT_Error    error;


  error = FT_Init_FreeType( &library );
  if ( error )
  {
    fprintf( stderr, "FT_Init_FreeType failed (0x%x)\n", error );
    return 1;
  }

  error = FT_New_Memory_Face( library,
                              font_data,
                              (FT_Long)sizeof ( font_data ),
                              0,
                              &face );
  if ( error )
  {
    fprintf( stderr, "FT_New_Memory_Face failed (0x%x)\n", error );
    FT_Done_FreeType( library );
    return 1;
  }

  /* glyph 2 is the variable composite; loading it parses the 'VARC' */
  /* component record and applies its axis overrides                 */
  error = FT_Load_Glyph( face, 2, FT_LOAD_NO_SCALE | FT_LOAD_NO_HINTING );
  if ( error )
    fprintf( stderr, "FT_Load_Glyph failed (0x%x)\n", error );
  else
    printf( "loaded glyph 2: %d points\n",
            face->glyph->outline.n_points );

  FT_Done_Face( face );
  FT_Done_FreeType( library );
  return 0;
}
