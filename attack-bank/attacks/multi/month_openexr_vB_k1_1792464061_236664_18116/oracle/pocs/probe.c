struct memfile
{
    const unsigned char* data;
    size_t               size;
};

static int64_t
mem_read (
    exr_const_context_t        ctxt,
    void*                      userdata,
    void*                      buffer,
    uint64_t                   sz,
    uint64_t                   offset,
    exr_stream_error_func_ptr_t error_cb)
{
    struct memfile* m = (struct memfile*) userdata;
    uint64_t        to_read;
    (void) ctxt;
    (void) error_cb;
    if (offset >= m->size) return 0;
    to_read = sz;
    if (offset + sz > m->size) to_read = (uint64_t) m->size - offset;
    memcpy (buffer, m->data + offset, to_read);
    return (int64_t) to_read;
}

static int64_t
mem_size (exr_const_context_t ctxt, void* userdata)
{
    (void) ctxt;
    return (int64_t) ((struct memfile*) userdata)->size;
}

/* ask the ASan runtime (when linked in) to turn reports into SIGABRT */
const char*
__asan_default_options (void)
{
    return "abort_on_error=1:detect_leaks=0";
}

int
main (void)
{
    struct memfile            mf = {kExrBytes, sizeof (kExrBytes)};
    exr_context_t             ctxt;
    exr_context_initializer_t cinit = EXR_DEFAULT_CONTEXT_INITIALIZER;
    exr_chunk_info_t          cinfo;

    cinit.read_fn   = mem_read;
    cinit.size_fn   = mem_size;
    cinit.user_data = &mf;

    if (exr_start_read (&ctxt, "probe.exr", &cinit) != EXR_ERR_SUCCESS)
        return 0;

    if (exr_read_scanline_chunk_info (ctxt, 0, 0, &cinfo) == EXR_ERR_SUCCESS)
    {
        exr_decode_pipeline_t decode = EXR_DECODE_PIPELINE_INITIALIZER;
        if (exr_decoding_initialize (ctxt, 0, &cinfo, &decode) ==
            EXR_ERR_SUCCESS)
        {
            int c;
            for (c = 0; c < decode.channel_count; ++c)
            {
                size_t sz = (size_t) decode.channels[c].width *
                            (size_t) decode.channels[c].height * 2u;
                decode.channels[c].decode_to_ptr = (uint8_t*) malloc (sz);
                decode.channels[c].user_pixel_stride = 2;
                decode.channels[c].user_line_stride =
                    decode.channels[c].width * 2;
            }
            if (exr_decoding_choose_default_routines (ctxt, 0, &decode) ==
                EXR_ERR_SUCCESS)
            {
                exr_decoding_run (ctxt, 0, &decode);
            }
            for (c = 0; c < decode.channel_count; ++c)
                free (decode.channels[c].decode_to_ptr);
            exr_decoding_destroy (ctxt, &decode);
        }
    }
    exr_finish (&ctxt);
    return 0;
}
