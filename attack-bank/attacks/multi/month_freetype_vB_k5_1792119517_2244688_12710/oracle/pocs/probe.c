int
main( void )
{
  FT_Library  library;
  FT_Face     face;
  FT_Error    error;


  error = FT_Init_FreeType( &library );
  if ( error )
    return 1;

  error = FT_New_Memory_Face( library,
                              font_data,
                              (FT_Long)sizeof ( font_data ),
                              0,
                              &face );
  if ( error )
    return 1;

  /* First load of the VARC composite glyph: initializes the private   */
  /* variation state used for the component-internal axes.             */
  error = FT_Load_Glyph( face, 1, FT_LOAD_NO_SCALE | FT_LOAD_NO_HINTING );
  if ( error )
    return 1;

  /* Second load: re-enters the same path with the private variation   */
  /* state already present on the face.                                */
  error = FT_Load_Glyph( face, 1, FT_LOAD_NO_SCALE | FT_LOAD_NO_HINTING );
  if ( error )
    return 1;

  FT_Done_Face( face );
  FT_Done_FreeType( library );

  return 0;
}
