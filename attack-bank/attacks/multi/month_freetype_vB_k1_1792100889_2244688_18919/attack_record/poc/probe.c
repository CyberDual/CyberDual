int
main( void )
{
  FT_Library  library;
  FT_Face     face;


  if ( FT_Init_FreeType( &library ) )
  {
    fprintf( stderr, "FT_Init_FreeType failed\n" );
    return 1;
  }

  if ( FT_New_Memory_Face( library,
                           font_data,
                           (FT_Long)sizeof ( font_data ),
                           0,
                           &face ) )
  {
    fprintf( stderr, "FT_New_Memory_Face failed\n" );
    return 1;
  }

  if ( FT_Load_Glyph( face, 1, FT_LOAD_NO_SCALE | FT_LOAD_NO_HINTING ) )
  {
    fprintf( stderr, "first FT_Load_Glyph failed\n" );
    return 1;
  }

  if ( FT_Load_Glyph( face, 1, FT_LOAD_NO_SCALE | FT_LOAD_NO_HINTING ) )
  {
    fprintf( stderr, "second FT_Load_Glyph failed\n" );
    return 1;
  }

  FT_Done_Face( face );
  FT_Done_FreeType( library );

  return 0;
}
