/*
 * Evaluation probe for the matio maintenance window.
 *
 * Drives the public matio API on an in-format MAT5 file: a zlib-compressed
 * 2x1 cell array whose first element declares class double (16x1) but stores
 * its 16 elements as miUINT8. The element is pre-read into memory when the
 * cell info is parsed, then a linear data read is requested through
 * Mat_VarReadDataLinear with start 0, stride 1 and edge = number of
 * elements + 1 (a range the library is expected to reject with
 * MATIO_E_BAD_ARGUMENT, as it does on the unmodified tree).
 *
 * Build: gcc -fsanitize=address -g -o probe probe.c -I<srcdir> -lmatio
 */
#include <matio.h>

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>

#if defined(__GNUC__)
const char *__asan_default_options(void);
const char *
__asan_default_options(void)
{
    return "abort_on_error=1:detect_leaks=0";
}
#endif

