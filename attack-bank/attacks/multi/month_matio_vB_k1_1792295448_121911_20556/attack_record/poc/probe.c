int
main(void)
{
    char path[] = "/tmp/matio_probe_XXXXXX";
    int fd = mkstemp(path);
    FILE *fp;
    mat_t *mat;
    matvar_t *cell, *x;
    double *out;
    int edge, err;
    size_t nelems, i;

    if ( fd < 0 ) {
        fprintf(stderr, "mkstemp failed\n");
        return 1;
    }
    fp = fdopen(fd, "wb");
    if ( NULL == fp ) {
        close(fd);
        unlink(path);
        return 1;
    }
    if ( fwrite(mat_file, 1, sizeof(mat_file), fp) != sizeof(mat_file) ) {
        fclose(fp);
        unlink(path);
        return 1;
    }
    fclose(fp);

    mat = Mat_Open(path, MAT_ACC_RDONLY);
    if ( NULL == mat ) {
        fprintf(stderr, "Mat_Open failed\n");
        unlink(path);
        return 1;
    }

    /* Info pass: compressed cell elements below the zlib-state threshold are
     * read into memory at this point. */
    cell = Mat_VarReadNextInfo(mat);
    if ( NULL == cell ) {
        fprintf(stderr, "Mat_VarReadNextInfo failed\n");
        Mat_Close(mat);
        unlink(path);
        return 1;
    }
    printf("cell: name=%s class=%d rank=%d dims=[%zu,%zu]\n", cell->name,
           (int)cell->class_type, cell->rank, cell->dims[0], cell->dims[1]);

    x = Mat_VarGetCell(cell, 0);
    if ( NULL == x ) {
        fprintf(stderr, "Mat_VarGetCell failed\n");
        Mat_VarFree(cell);
        Mat_Close(mat);
        unlink(path);
        return 1;
    }
    nelems = 1;
    for ( i = 0; i < (size_t)x->rank; i++ )
        nelems *= x->dims[i];
    printf("x: name=%s class=%d type=%d dims=[%zu,%zu] nbytes=%zu\n", x->name,
           (int)x->class_type, (int)x->data_type, x->dims[0], x->dims[1], x->nbytes);

    edge = (int)nelems + 1;
    out = (double *)calloc((size_t)edge, sizeof(double));
    if ( NULL == out ) {
        Mat_VarFree(cell);
        Mat_Close(mat);
        unlink(path);
        return 1;
    }
    err = Mat_VarReadDataLinear(mat, x, out, 0, 1, edge);
    printf("Mat_VarReadDataLinear(start=0, stride=1, edge=%d) -> %d\n", edge, err);

    free(out);
    Mat_VarFree(cell);
    Mat_Close(mat);
    unlink(path);
    return 0;
}
