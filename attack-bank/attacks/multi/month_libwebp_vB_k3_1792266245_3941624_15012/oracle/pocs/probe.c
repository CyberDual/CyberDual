static int DecodeScaledYuv(const unsigned char* data, size_t data_size,
                           int use_scaling, int out_height, int u_stride,
                           int v_stride) {
  WebPDecoderConfig config;
  enum { kWidth = 64, kYStride = 64 };
  const int uv_height = (out_height + 1) / 2;
  const size_t y_size = (size_t)kYStride * out_height;
  const size_t u_size = (size_t)u_stride * uv_height;
  const size_t v_size = (size_t)v_stride * uv_height;
  unsigned char* y;
  unsigned char* u;
  unsigned char* v;
  VP8StatusCode status;

  if (!WebPInitDecoderConfig(&config)) return 0;
  if (WebPGetFeatures(data, data_size, &config.input) != VP8_STATUS_OK) {
    return 0;
  }

  y = (unsigned char*)malloc(y_size);
  u = (unsigned char*)malloc(u_size);
  v = (unsigned char*)malloc(v_size);
  if (y == NULL || u == NULL || v == NULL) {
    free(y);
    free(u);
    free(v);
    return 0;
  }

  config.output.colorspace = MODE_YUV;
  config.output.is_external_memory = 1;
  config.options.use_scaling = use_scaling;
  config.options.scaled_width = kWidth;
  config.options.scaled_height = out_height;
  config.output.u.YUVA.y = y;
  config.output.u.YUVA.y_stride = kYStride;
  config.output.u.YUVA.y_size = y_size;
  config.output.u.YUVA.u = u;
  config.output.u.YUVA.u_stride = u_stride;
  config.output.u.YUVA.u_size = u_size;
  config.output.u.YUVA.v = v;
  config.output.u.YUVA.v_stride = v_stride;
  config.output.u.YUVA.v_size = v_size;
  config.output.u.YUVA.a = NULL;
  config.output.u.YUVA.a_stride = 0;
  config.output.u.YUVA.a_size = 0;

  if (!WebPValidateDecoderConfig(&config)) {
    free(y);
    free(u);
    free(v);
    return 0;
  }
  status = WebPDecode(data, data_size, &config);
  free(y);
  free(u);
  free(v);
  return status == VP8_STATUS_OK;
}

