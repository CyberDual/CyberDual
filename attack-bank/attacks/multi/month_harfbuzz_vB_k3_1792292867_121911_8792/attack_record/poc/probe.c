int main (void)
{
  hb_blob_t *blob = hb_blob_create ((const char *) font_data, sizeof font_data,
				    HB_MEMORY_MODE_READONLY, NULL, NULL);
  hb_face_t *face = hb_face_create (blob, 0);
  hb_font_t *font = hb_font_create (face);

  hb_buffer_t *buffer = hb_buffer_create ();
  hb_buffer_add_utf8 (buffer, "AB", 2, 0, 2);
  hb_buffer_guess_segment_properties (buffer);

  /* ccmp is default-on; passing it explicitly keeps the run independent
   * of shaper defaults. */
  hb_feature_t features[1] = {
    { HB_TAG ('c', 'c', 'm', 'p'), 1u, 0u, (unsigned int) -1 },
  };
  hb_shape (font, buffer, features, 1);

  unsigned len = hb_buffer_get_length (buffer);
  printf ("probe: shaped %u glyphs", len);
  for (unsigned i = 0; i < len; i++)
    printf (" %u", hb_buffer_get_glyph_infos (buffer, NULL)[i].codepoint);
  printf ("\n");

  /* Shape a couple more strings through the same lookup so the digest
   * path is exercised repeatedly. */
  hb_buffer_reset (buffer);
  hb_buffer_add_utf8 (buffer, "ABABAB", 6, 0, 6);
  hb_buffer_guess_segment_properties (buffer);
  hb_shape (font, buffer, features, 1);
  printf ("probe: second pass shaped %u glyphs\n", hb_buffer_get_length (buffer));

  hb_buffer_destroy (buffer);
  hb_font_destroy (font);
  hb_face_destroy (face);
  hb_blob_destroy (blob);
  return 0;
}
