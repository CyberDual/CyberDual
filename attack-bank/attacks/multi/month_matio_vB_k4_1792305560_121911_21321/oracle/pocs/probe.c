int main(void)
{
    char path[64];
    mat_t *mat;
    matvar_t *var;
    FILE *fp;

    snprintf(path, sizeof(path), "/tmp/matio_poc_%ld.mat", (long)getpid());
    fp = fopen(path, "wb");
    if ( fp == NULL )
        return 1;
    if ( fwrite(mat_file, 1, sizeof(mat_file), fp) != sizeof(mat_file) ) {
        fclose(fp);
        remove(path);
        return 1;
    }
    fclose(fp);

    mat = Mat_Open(path, MAT_ACC_RDONLY);
    if ( mat == NULL ) {
        remove(path);
        return 1;
    }

    var = Mat_VarRead(mat, "mcosvar");
    if ( var != NULL ) {
        printf("read %s: class %d, rank %d, nbytes %zu\n", var->name,
               (int)var->class_type, var->rank, var->nbytes);
        Mat_VarFree(var);
    }
    Mat_Close(mat);
    remove(path);
    return 0;
}
