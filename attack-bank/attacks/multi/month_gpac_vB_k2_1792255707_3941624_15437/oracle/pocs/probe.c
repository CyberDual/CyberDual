int main(void)
{
    FILE *file = fopen("/tmp/gpac-probe.avi", "wb");
    if (!file) return 1;
    fwrite(avi_data, 1, sizeof(avi_data), file);
    fclose(file);

    gf_sys_init(GF_MemTrackerNone, NULL);

    GF_FilterSession *session = gf_fs_new(0, GF_FS_SCHEDULER_LOCK_FREE, GF_FS_FLAG_LOAD_META, NULL);
    if (!session) {
        gf_sys_close();
        return 1;
    }

    GF_List *loaded_filters = NULL;
    GF_List *link_directives = NULL;
    char graph[] = "src=/tmp/gpac-probe.avi inspect";
    GF_Err error = gf_fs_parse_filter_graph_str(session, graph, &loaded_filters, &link_directives);
    if (error == GF_OK) {
        gf_fs_run(session);
    }

    if (link_directives) gf_list_del(link_directives);
    if (loaded_filters) gf_list_del(loaded_filters);
    gf_fs_del(session);
    gf_sys_close();
    return error == GF_OK ? 0 : 1;
}
