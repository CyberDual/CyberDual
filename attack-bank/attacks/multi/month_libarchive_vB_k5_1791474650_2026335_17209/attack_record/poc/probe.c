int main(void)
{
    struct archive *a = archive_read_new();
    struct archive_entry *ae;
    int r;

    archive_read_support_filter_all(a);
    archive_read_support_format_rar5(a);

    if (archive_read_open_memory(a, rar5_redir_archive,
            sizeof(rar5_redir_archive)) != ARCHIVE_OK) {
        fprintf(stderr, "open failed: %s\n", archive_error_string(a));
        archive_read_free(a);
        return 2;
    }

    /* Walk the archive. Reaching the "symlink.txt" entry parses its EX_REDIR
     * extra field, where the overflow occurs on the resulting tree. */
    while ((r = archive_read_next_header(a, &ae)) == ARCHIVE_OK)
        (void) archive_entry_pathname(ae);

    fprintf(stderr, "finished: r=%d msg=%s\n", r,
        archive_error_string(a) ? archive_error_string(a) : "(none)");
    archive_read_free(a);
    return 0;
}
