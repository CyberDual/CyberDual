int main(void)
{
	struct archive *a;
	struct archive_entry *ae;
	int r;

	a = archive_read_new();
	if (a == NULL) {
		fprintf(stderr, "archive_read_new failed\n");
		return (1);
	}
	if (archive_read_support_format_rar5(a) != ARCHIVE_OK) {
		fprintf(stderr, "support_format_rar5 failed\n");
		archive_read_free(a);
		return (1);
	}

	r = archive_read_open_memory(a, rar5_stream, sizeof(rar5_stream));
	if (r != ARCHIVE_OK) {
		fprintf(stderr, "open: %d (%s)\n", r, archive_error_string(a));
		archive_read_free(a);
		return (1);
	}

	r = archive_read_next_header(a, &ae);
	fprintf(stderr, "next_header: %d (%s)\n", r,
	    r == ARCHIVE_OK ? "ok" : archive_error_string(a));

	archive_read_free(a);
	return (0);
}
