#define FONT_LEN 384

int
main( void )
{
  FT_Library  library;
  FT_Face     face;
  FT_Error    error;


  error = FT_Init_FreeType( &library );
  if ( error )
  {
    printf( "FT_Init_FreeType failed: %d\n", error );
    return 1;
  }

  error = FT_New_Memory_Face( library,
                              font_data,
                              FONT_LEN,
                              0,
                              &face );
  if ( error )
  {
    printf( "FT_New_Memory_Face failed: %d\n", error );
    return 1;
  }

  printf( "face loaded: %ld glyphs\n", (long)face->num_glyphs );

  error = FT_Set_Char_Size( face, 0, 16 * 64, 72, 72 );
  if ( error )
    printf( "FT_Set_Char_Size failed: %d\n", error );

  error = FT_Load_Glyph( face, 1, FT_LOAD_DEFAULT );
  if ( error )
    printf( "FT_Load_Glyph failed: %d\n", error );
  else
    printf( "glyph loaded: %ld points\n",
            (long)face->glyph->outline.n_points );

  FT_Done_Face( face );
  FT_Done_FreeType( library );

  printf( "probe done\n" );
  return 0;
}
