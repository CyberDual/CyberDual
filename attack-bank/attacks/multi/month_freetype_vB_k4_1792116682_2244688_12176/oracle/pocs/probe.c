int
main( void )
{
  FT_Library  library;
  FT_Face     face;
  FT_Error    error;


  error = FT_Init_FreeType( &library );
  if ( error )
  {
    fprintf( stderr, "FT_Init_FreeType failed: %d\n", error );
    return 1;
  }

  error = FT_New_Memory_Face( library,
                              (const FT_Byte*)probe_font,
                              (FT_Long)sizeof( probe_font ),
                              0,
                              &face );
  if ( error )
  {
    fprintf( stderr, "FT_New_Memory_Face failed: %d\n", error );
    FT_Done_FreeType( library );
    return 0;
  }

  /* exercise the face a little */
  FT_Load_Glyph( face, 0, FT_LOAD_DEFAULT );
  FT_Load_Glyph( face, 1, FT_LOAD_DEFAULT );

  printf( "loaded face: %s (%ld glyphs)\n",
          face->family_name ? face->family_name : "?",
          face->num_glyphs );

  FT_Done_Face( face );
  FT_Done_FreeType( library );

  return 0;
}
