/*
 * PoC for the delocalized QuickTime image-description defect.
 *
 * Drives the public Exiv2 API (ImageFactory::open + Image::readMetadata)
 * with an in-contract QuickTime/MOV file: a minimal moov/mdia containing a
 * vmhd atom (selects the video stream) and an stsd sample description whose
 * image description carries a 32-byte compressor name with no NUL byte.
 *
 * On the original batch this parses cleanly. On the modified tree the
 * image-description buffer is sized to exactly the largest read (32 bytes),
 * so the C-string extraction of the compressor name runs off the end of the
 * heap buffer and AddressSanitizer aborts with a heap-buffer-overflow READ.
 *
 * Build (C++ library, so compile as C++ despite the .c name):
 *   c++ -std=c++17 probe.c -I<exiv2-include> -lexiv2 -fsanitize=address -o probe
 */
