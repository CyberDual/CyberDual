int main(void)
{
  struct heif_context* ctx = heif_context_alloc();
  struct heif_error err = heif_context_read_from_memory_without_copy(ctx, kImage, sizeof(kImage), NULL);
  if (err.code != heif_error_Ok) {
    fprintf(stderr, "read %d/%d\n", err.code, err.subcode);
    return 1;
  }

  struct heif_image_handle* handle = NULL;
  err = heif_context_get_primary_image_handle(ctx, &handle);
  if (err.code != heif_error_Ok) {
    fprintf(stderr, "handle %d/%d\n", err.code, err.subcode);
    return 1;
  }

  struct heif_decoding_options* opt = heif_decoding_options_alloc();
  struct heif_color_conversion_options_ext* ext = heif_color_conversion_options_ext_alloc();
  ext->alpha_composition_mode = heif_alpha_composition_mode_checkerboard;
  ext->checkerboard_square_size = 40000;
  ext->background_red = 0xFFFF;
  ext->background_green = 0x0000;
  ext->background_blue = 0x8080;
  ext->secondary_background_red = 0x0000;
  ext->secondary_background_green = 0xFFFF;
  ext->secondary_background_blue = 0x0000;
  opt->color_conversion_options_ext = ext;

  struct heif_image* img = NULL;
  err = heif_decode_image(handle, &img, heif_colorspace_RGB, heif_chroma_444, opt);

  heif_color_conversion_options_ext_free(ext);
  heif_decoding_options_free(opt);
  if (img) heif_image_release(img);
  heif_image_handle_release(handle);
  heif_context_free(ctx);

  if (err.code != heif_error_Ok) {
    fprintf(stderr, "decode %d/%d\n", err.code, err.subcode);
    return 1;
  }
  return 0;
}
