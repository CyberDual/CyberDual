/*
 * Reads a 7z archive whose single file is stored with the Delta
 * filter (distance 4) on top of Deflate.  The file unpacks to
 * 70000 bytes, so decoding crosses the reader's 64 KiB sliding
 * window; the byte-wise delta step then touches memory it should
 * not, which AddressSanitizer reports as a heap-buffer-overflow.
 *
 * The archive bytes are embedded below; only libarchive's public
 * API is used.
 */
