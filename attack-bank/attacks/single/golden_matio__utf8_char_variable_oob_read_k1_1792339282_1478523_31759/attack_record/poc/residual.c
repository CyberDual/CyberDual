int main(void)
{
    const char *path = "residual_input.mat";
    FILE *f = fopen(path, "wb");
    if ( f == NULL ) {
        perror("fopen");
        return 2;
    }
    fwrite(crafted_mat, 1, sizeof(crafted_mat), f);
    fclose(f);

    mat_t *mat = Mat_Open(path, MAT_ACC_RDONLY);
    if ( mat == NULL ) {
        fprintf(stderr, "Mat_Open failed\n");
        return 2;
    }

    matvar_t *matvar;
    while ( NULL != (matvar = Mat_VarReadNext(mat)) ) {
        if ( matvar->class_type == MAT_C_CHAR && matvar->data_type == MAT_T_UTF8 &&
             matvar->data != NULL ) {
            /* round-trip the character data through the public create API */
            matvar_t *copy = Mat_VarCreate(matvar->name, MAT_C_CHAR, MAT_T_UTF8, matvar->rank,
                                           matvar->dims, matvar->data, 0);
            Mat_VarFree(copy);
        }
        Mat_VarFree(matvar);
    }
    Mat_Close(mat);
    printf("done\n");
    return 0;
}
