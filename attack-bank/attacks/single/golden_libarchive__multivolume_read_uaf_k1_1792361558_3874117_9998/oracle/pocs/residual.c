static void
write_file(const char *dir, const char *name, const unsigned char *data, size_t len)
{
	char path[4096];
	FILE *f;

	snprintf(path, sizeof(path), "%s/%s", dir, name);
	f = fopen(path, "wb");
	if (f == NULL) {
		perror("fopen");
		exit(2);
	}
	if (fwrite(data, 1, len, f) != len) {
		perror("fwrite");
		exit(2);
	}
	fclose(f);
}

int
main(void)
{
	char dir[] = "/tmp/splitvolXXXXXX";
	static char vol1_path[4096], vol2_path[4096];
	const char *filenames[3];
	struct archive *a;
	struct archive_entry *ae;
	int r;

	if (mkdtemp(dir) == NULL) {
		perror("mkdtemp");
		return (2);
	}
	write_file(dir, "split_1.tar", vol1, VOL1_LEN);
	write_file(dir, "split_2.tar", vol2, VOL2_LEN);

	snprintf(vol1_path, sizeof(vol1_path), "%s/split_1.tar", dir);
	snprintf(vol2_path, sizeof(vol2_path), "%s/split_2.tar", dir);
	filenames[0] = vol1_path;
	filenames[1] = vol2_path;
	filenames[2] = NULL;

	a = archive_read_new();
	if (a == NULL)
		return (2);
	archive_read_support_filter_uu(a);
	archive_read_support_format_tar(a);

	r = archive_read_open_filenames(a, filenames, 4096);
	printf("open_filenames: %d\n", r);

	r = archive_read_next_header(a, &ae);
	printf("next_header: %d, name: %s\n", r,
	    r == ARCHIVE_OK ? archive_entry_pathname(ae) : "-");

	r = archive_read_next_header(a, &ae);
	printf("next_header: %d\n", r);

	archive_read_free(a);
	unlink(vol1_path);
	unlink(vol2_path);
	rmdir(dir);
	printf("done\n");
	return (0);
}
