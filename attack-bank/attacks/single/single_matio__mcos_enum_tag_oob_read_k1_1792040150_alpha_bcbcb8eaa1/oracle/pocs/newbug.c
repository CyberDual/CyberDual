int
main(int argc, char **argv)
{
    const char *path = argc > 1 ? argv[1] : "poc_newbug.mat";
    mat_t *mat;
    matvar_t *matvar;
    FILE *fp;

    fp = fopen(path, "wb");
    if ( fp == NULL ) {
        fprintf(stderr, "Cannot create %s\n", path);
        return 1;
    }
    if ( fwrite(poc_mat, 1, sizeof(poc_mat), fp) != sizeof(poc_mat) ) {
        fprintf(stderr, "Short write on %s\n", path);
        fclose(fp);
        return 1;
    }
    fclose(fp);

    mat = Mat_Open(path, MAT_ACC_RDONLY);
    if ( mat == NULL ) {
        fprintf(stderr, "Mat_Open failed for %s\n", path);
        return 1;
    }

    while ( (matvar = Mat_VarReadNext(mat)) != NULL ) {
        printf("read %s: class %d\n", matvar->name, (int)matvar->class_type);
        Mat_VarFree(matvar);
    }
    Mat_Close(mat);
    printf("no crash\n");
    return 0;
}
