int
main( void )
{
  FT_Library  library;
  FT_Face     face;
  FT_Fixed    advance = 0;
  FT_Error    error;


  error = FT_Init_FreeType( &library );
  if ( error )
    return 1;

  error = FT_New_Memory_Face( library,
                              font_data,
                              (FT_Long)sizeof ( font_data ),
                              0,
                              &face );
  if ( error )
  {
    FT_Done_FreeType( library );
    return 1;
  }

  error = FT_Set_Named_Instance( face, 1 );
  if ( error )
  {
    FT_Done_Face( face );
    FT_Done_FreeType( library );
    return 1;
  }

  error = FT_Get_Advance( face, 0, FT_LOAD_NO_SCALE, &advance );
  (void)error;
  (void)advance;

  FT_Done_Face( face );
  FT_Done_FreeType( library );
  return 0;
}
