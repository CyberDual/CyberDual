int
main( void )
{
  FT_Library       library;
  FT_Face          face;
  BDF_PropertyRec  property;
  FT_Error         error;
  char             path[] = "/tmp/ftbdf-XXXXXX";
  char*            name;
  FILE*            file;
  int              fd;

  fd = mkstemp( path );
  if ( fd < 0 )
    return 1;

  file = fdopen( fd, "wb" );
  if ( !file || fwrite( font, 1, sizeof ( font ), file ) != sizeof ( font ) )
    return 2;
  fclose( file );

  name = malloc( 2 );
  if ( !name )
    return 3;
  name[0] = 'A';
  name[1] = 0;

  error = FT_Init_FreeType( &library );
  if ( error )
    return 4;
  error = FT_New_Face( library, path, 0, &face );
  if ( error )
    return 5;
  error = FT_Set_Pixel_Sizes( face, 0, 12 );
  if ( error )
    return 6;

  error = FT_Get_BDF_Property( face, name, &property );
  printf( "property: %d\n", error );

  FT_Done_Face( face );
  FT_Done_FreeType( library );
  free( name );
  unlink( path );
  return 0;
}
