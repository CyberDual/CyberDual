struct vol {
	const unsigned char *data;
	size_t size;
	size_t off;
	unsigned char *buf;
	size_t bsize;
};

static int
vol_open(struct archive *a, void *cd)
{
	struct vol *v = cd;

	(void)a;
	v->off = 0;
	v->buf = malloc(v->bsize);
	if (v->buf == NULL)
		return (ARCHIVE_FATAL);
	return (ARCHIVE_OK);
}

static la_ssize_t
vol_read(struct archive *a, void *cd, const void **buff)
{
	struct vol *v = cd;
	size_t n;

	(void)a;
	if (v->off >= v->size)
		return (0);
	n = v->size - v->off;
	if (n > v->bsize)
		n = v->bsize;
	memcpy(v->buf, v->data + v->off, n);
	v->off += n;
	*buff = v->buf;
	return ((la_ssize_t)n);
}

static int
vol_close(struct archive *a, void *cd)
{
	struct vol *v = cd;

	(void)a;
	free(v->buf);
	v->buf = NULL;
	return (ARCHIVE_OK);
}

int
main(void)
{
	struct vol vols[2];
	struct archive *a;
	struct archive_entry *ae;
	char buf[64];
	int r;

	memset(vols, 0, sizeof(vols));
	vols[0].data = vol1_bytes;
	vols[0].size = sizeof(vol1_bytes);
	vols[0].bsize = 4096;
	vols[1].data = vol2_bytes;
	vols[1].size = sizeof(vol2_bytes);
	vols[1].bsize = 4096;

	a = archive_read_new();
	if (a == NULL)
		return (1);
	archive_read_support_filter_uu(a);
	archive_read_support_format_tar(a);
	archive_read_set_open_callback(a, vol_open);
	archive_read_set_read_callback(a, vol_read);
	archive_read_set_close_callback(a, vol_close);
	if (archive_read_append_callback_data(a, &vols[0]) != ARCHIVE_OK ||
	    archive_read_append_callback_data(a, &vols[1]) != ARCHIVE_OK)
		return (1);
	r = archive_read_open1(a);
	if (r != ARCHIVE_OK) {
		fprintf(stderr, "open failed: %s\n", archive_error_string(a));
		archive_read_free(a);
		return (1);
	}
	r = archive_read_next_header(a, &ae);
	if (r != ARCHIVE_OK) {
		fprintf(stderr, "header failed: %s\n", archive_error_string(a));
		archive_read_free(a);
		return (1);
	}
	if (archive_read_data(a, buf, sizeof(buf)) < 0) {
		fprintf(stderr, "data failed: %s\n", archive_error_string(a));
		archive_read_free(a);
		return (1);
	}
	archive_read_free(a);
	return (0);
}
