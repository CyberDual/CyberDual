// Public-API reproducer: 1-bit OS/2 BITMAPCOREHEADER BMP (8x1).

#include <exiv2/exiv2.hpp>

#include <cstdint>
#include <iostream>

int main() {
  // 1-bit OS/2 BMP: BITMAPFILEHEADER + BITMAPCOREHEADER + 2 RGBTRIPLEs + 12 padded rows.
  // 80 bytes so the usual image-type sniffers can examine the prefix and seek back.
  const uint8_t bmp[] = {
      'B',  'M',  0x50, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x20, 0x00, 0x00, 0x00, 0x0c, 0x00, 0x00, 0x00,
      0x08, 0x00, 0x0c, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  };

  auto image = Exiv2::ImageFactory::open(bmp, sizeof(bmp));
  if (!image) {
    return 1;
  }
  image->readMetadata();
  std::cout << image->pixelWidth() << "x" << image->pixelHeight() << "\n";
  return 0;
}
