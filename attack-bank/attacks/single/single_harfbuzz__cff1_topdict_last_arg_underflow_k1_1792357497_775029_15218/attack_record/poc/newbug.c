int
main (void)
{
  hb_blob_t *blob = hb_blob_create ((const char *) font_data,
                                    (unsigned int) sizeof (font_data),
                                    HB_MEMORY_MODE_READONLY, NULL, NULL);
  hb_face_t *face = hb_face_create (blob, 0);
  hb_blob_destroy (blob);

  /* Exercise the load path (top DICT is parsed here). */
  hb_font_t *font = hb_font_create (face);
  hb_ot_font_set_funcs (font);
  (void) hb_face_get_upem (face);
  hb_font_destroy (font);

  /* Exercise the subset path (top DICT is re-serialized here). */
  hb_subset_input_t *input = hb_subset_input_create_or_fail ();
  hb_face_t *out = hb_subset_or_fail (face, input);
  if (out)
    hb_face_destroy (out);
  if (input)
    hb_subset_input_destroy (input);

  hb_face_destroy (face);
  return 0;
}
