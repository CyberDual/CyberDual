static int
write_file(const char *path, const unsigned char *data, size_t size)
{
	FILE *file = fopen(path, "wb");
	if (file == NULL)
		return (-1);
	if (fwrite(data, 1, size, file) != size) {
		fclose(file);
		return (-1);
	}
	return (fclose(file) == 0 ? 0 : -1);
}

int
main(void)
{
	char directory[] = "/tmp/libarchive-uaf-XXXXXX";
	const char *filenames[3];
	char path1[64], path2[64];
	struct archive *archive;
	struct archive_entry *entry;
	int result = 0;

	if (mkdtemp(directory) == NULL)
		return (1);
	snprintf(path1, sizeof(path1), "%s/volume1.tar", directory);
	snprintf(path2, sizeof(path2), "%s/volume2.tar", directory);
	if (write_file(path1, volume1, sizeof(volume1)) != 0 ||
	    write_file(path2, volume2, sizeof(volume2)) != 0) {
		rmdir(directory);
		return (1);
	}

	filenames[0] = path1;
	filenames[1] = path2;
	filenames[2] = NULL;

	archive = archive_read_new();
	if (archive == NULL ||
	    archive_read_support_filter_uu(archive) != ARCHIVE_OK ||
	    archive_read_support_format_tar(archive) != ARCHIVE_OK ||
	    archive_read_open_filenames(archive, filenames, 4096) != ARCHIVE_OK ||
	    archive_read_next_header(archive, &entry) != ARCHIVE_OK ||
	    archive_read_next_header(archive, &entry) != ARCHIVE_RETRY)
		result = 1;

	if (archive != NULL)
		archive_read_free(archive);
	unlink(path1);
	unlink(path2);
	rmdir(directory);
	return (result);
}
