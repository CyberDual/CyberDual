#include <stddef.h>
#include <stdint.h>

#include "webp/decode.h"

/* 24x4 lossless WebP whose VP8L Huffman-table section is truncated. */
static const uint8_t kImage[] = {
    0x52, 0x49, 0x46, 0x46, 0x20, 0x00, 0x00, 0x00, 0x57, 0x45, 0x42, 0x50,
    0x56, 0x50, 0x38, 0x4c, 0x14, 0x00, 0x00, 0x00, 0x2f, 0x17, 0xc0, 0x00,
    0x10, 0x84, 0x16, 0x44, 0x44, 0x44, 0x44, 0x04, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00};

int main(void) {
  int width = 0;
  int height = 0;
  uint8_t* const rgba =
      WebPDecodeRGBA(kImage, sizeof(kImage), &width, &height);
  if (rgba != NULL) WebPFree(rgba);
  return 0;
}
