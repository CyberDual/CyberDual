#include <lzma.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>

static const uint8_t stream_data[] = {
    0xfd, 0x37, 0x7a, 0x58, 0x5a, 0x00, 0x00, 0x04, 0xe6, 0xd6, 0xb4, 0x46, 0x02, 0x00, 0x21, 0x01, 0x16, 0x00, 0x00, 0x00, 0x74, 0x2f, 0xe5, 0xa3, 0xe0, 0x00, 0xdb, 0x00, 0x11, 0x5d, 0x00, 0x34, 0x19, 0x49, 0xee, 0x8d, 0xe9, 0x17, 0x89, 0x3a, 0x33, 0x60, 0x09, 0xed, 0xbc, 0x43, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x3b, 0x36, 0x98, 0x1d, 0x9c, 0x22, 0x4d, 0x47, 0x00, 0x01, 0x2d, 0xdc, 0x01, 0x00, 0x00, 0x00, 0x08, 0x37, 0xde, 0x8c, 0xb1, 0xc4, 0x67, 0xfb, 0x02, 0x00, 0x00, 0x00, 0x00, 0x04, 0x59, 0x5a
};

int main(void)
{
    const size_t first_size = 30;
    uint8_t *first = malloc(first_size);
    if (first == NULL)
        return 2;
    memcpy(first, stream_data, first_size);
    first[28] = 0;

    lzma_stream stream = LZMA_STREAM_INIT;
    if (lzma_stream_decoder(&stream, 300 << 20, 0) != LZMA_OK) {
        free(first);
        return 2;
    }

    uint8_t output[512];
    stream.next_in = first;
    stream.avail_in = first_size;
    stream.next_out = output;
    stream.avail_out = sizeof(output);
    lzma_ret ret = lzma_code(&stream, LZMA_RUN);
    if (ret != LZMA_OK || stream.avail_in != 0) {
        lzma_end(&stream);
        free(first);
        return 2;
    }

    stream.next_in = stream_data + first_size;
    stream.avail_in = sizeof(stream_data) - first_size;
    do {
        ret = lzma_code(&stream, LZMA_FINISH);
    } while (ret == LZMA_OK && stream.avail_out != 0);

    lzma_end(&stream);
    free(first);
    return ret == LZMA_DATA_ERROR ? 0 : 2;
}
