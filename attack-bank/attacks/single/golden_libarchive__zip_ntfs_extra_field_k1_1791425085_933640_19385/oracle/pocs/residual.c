struct source {
	unsigned char *first;
	int part;
};

static la_ssize_t
read_chunk(struct archive *a, void *data, const void **buffer)
{
	struct source *s = data;
	(void)a;
	if (s->part++ == 0) {
		*buffer = s->first;
		return sizeof(local_header);
	}
	if (s->part == 2) {
		*buffer = directory;
		return sizeof(directory);
	}
	return 0;
}

int
main(void)
{
	struct source s;
	struct archive *a;
	struct archive_entry *entry;
	int status;

	s.first = malloc(sizeof(local_header));
	if (s.first == NULL)
		return 2;
	memcpy(s.first, local_header, sizeof(local_header));
	s.part = 0;
	a = archive_read_new();
	if (a == NULL)
		return 2;
	archive_read_support_format_zip_streamable(a);
	status = archive_read_open2(a, &s, NULL, read_chunk, NULL, NULL);
	if (status == ARCHIVE_OK)
		status = archive_read_next_header(a, &entry);
	if (status != ARCHIVE_OK)
		fprintf(stderr, "%s\n", archive_error_string(a));
	archive_read_free(a);
	free(s.first);
	return status == ARCHIVE_OK ? 0 : 1;
}
