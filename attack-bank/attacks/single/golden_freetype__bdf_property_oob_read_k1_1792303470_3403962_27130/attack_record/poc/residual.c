static int
check_benign( FT_Library  library )
{
  FT_Face          face;
  FT_Error         error;
  BDF_PropertyRec  prop;
  unsigned char*   buf;
  int              rc = 1;


  buf = (unsigned char*)malloc( sizeof ( font_benign ) );
  if ( !buf )
    return 1;
  memcpy( buf, font_benign, sizeof ( font_benign ) );

  error = FT_New_Memory_Face( library, buf, sizeof ( font_benign ), 0,
                              &face );
  if ( error )
  {
    fprintf( stderr, "benign: FT_New_Memory_Face failed (%d)\n", error );
    goto Fail;
  }

  error = FT_Set_Pixel_Sizes( face, 0, 16 );
  if ( error )
  {
    fprintf( stderr, "benign: FT_Set_Pixel_Sizes failed (%d)\n", error );
    goto Fail;
  }

  error = FT_Get_BDF_Property( face, "A", &prop );
  if ( error                                ||
       prop.type != BDF_PROPERTY_TYPE_ATOM  ||
       strcmp( prop.u.atom, "V" )           )
  {
    fprintf( stderr, "benign: property A lookup failed (%d)\n", error );
    goto Fail;
  }

  error = FT_Get_BDF_Property( face, "N", &prop );
  if ( error                                  ||
       prop.type != BDF_PROPERTY_TYPE_INTEGER ||
       prop.u.integer != 42                   )
  {
    fprintf( stderr, "benign: property N lookup failed (%d)\n", error );
    goto Fail;
  }

  error = FT_Get_BDF_Property( face, "DOES_NOT_EXIST", &prop );
  if ( !error || prop.type != BDF_PROPERTY_TYPE_NONE )
  {
    fprintf( stderr, "benign: missing property lookup misbehaved\n" );
    goto Fail;
  }

  printf( "benign font: all BDF property checks passed\n" );
  rc = 0;

Fail:
  FT_Done_Face( face );
  free( buf );
  return rc;
}


int
main( void )
{
  FT_Library       library;
  FT_Face          face;
  FT_Error         error;
  BDF_PropertyRec  prop;
  unsigned char*   buf;


  error = FT_Init_FreeType( &library );
  if ( error )
  {
    fprintf( stderr, "FT_Init_FreeType failed (%d)\n", error );
    return 1;
  }

  if ( check_benign( library ) )
    return 1;

  buf = (unsigned char*)malloc( sizeof ( font_crafted ) );
  if ( !buf )
    return 1;
  memcpy( buf, font_crafted, sizeof ( font_crafted ) );

  error = FT_New_Memory_Face( library, buf, sizeof ( font_crafted ), 0,
                              &face );
  if ( error )
  {
    fprintf( stderr, "crafted: FT_New_Memory_Face failed (%d)\n", error );
    return 1;
  }

  error = FT_Set_Pixel_Sizes( face, 0, 16 );
  if ( error )
  {
    fprintf( stderr, "crafted: FT_Set_Pixel_Sizes failed (%d)\n", error );
    return 1;
  }

  fprintf( stderr, "crafted: querying BDF property \"A\"...\n" );
  fflush( stderr );

  error = FT_Get_BDF_Property( face, "A", &prop );

  fprintf( stderr, "crafted: lookup returned %d, type %d\n",
           error, (int)prop.type );

  FT_Done_Face( face );
  free( buf );
  FT_Done_FreeType( library );

  printf( "done (no crash)\n" );
  return 0;
}
