int main (void)
{
  hb_blob_t *blob = hb_blob_create ((const char *) font_data, sizeof (font_data),
				    HB_MEMORY_MODE_READONLY, NULL, NULL);
  hb_face_t *face = hb_face_create (blob, 0);

  hb_subset_input_t *input = hb_subset_input_create_or_fail ();
  if (!input) return 2;
  hb_set_add_range (hb_subset_input_glyph_set (input), 0, 1);

  hb_face_t *result = hb_subset_or_fail (face, input);
  if (result)
  {
    unsigned int length = 0;
    const char *data = hb_blob_get_data (hb_face_reference_blob (result), &length);
    unsigned int nonzero = 0;
    for (unsigned int i = 0; i < length; i++)
      if (data[i]) nonzero++;
    printf ("subset ok: %u bytes (%u nonzero)\n", length, nonzero);
    hb_face_destroy (result);
  }
  else
    printf ("subset failed\n");

  hb_subset_input_destroy (input);
  hb_face_destroy (face);
  hb_blob_destroy (blob);
  return 0;
}
