#include <stdio.h>
#include <stdlib.h>
#include <hb.h>
#include <hb-ot.h>
#include <hb-subset.h>

static const unsigned char font_data[] = {
  0x4f, 0x54, 0x54, 0x4f, 0x00, 0x02, 0x00, 0x20, 0x00, 0x01, 0x00, 0x00, 0x6d, 0x61, 0x78, 0x70,
  0x00, 0x01, 0x50, 0x00, 0x00, 0x00, 0x00, 0x2c, 0x00, 0x00, 0x00, 0x06, 0x43, 0x46, 0x46, 0x20,
  0x24, 0x6f, 0x24, 0x3f, 0x00, 0x00, 0x00, 0x34, 0x00, 0x00, 0x00, 0x2a, 0x00, 0x00, 0x50, 0x00,
  0x00, 0x01, 0x00, 0x00, 0x01, 0x00, 0x04, 0x01, 0x00, 0x01, 0x01, 0x01, 0x02, 0x41, 0x00, 0x01,
  0x01, 0x01, 0x12, 0x1d, 0x00, 0x00, 0x00, 0x00, 0x1d, 0x00, 0x00, 0x00, 0x01, 0x1d, 0x00, 0x00,
  0x00, 0x00, 0x0c, 0x1e, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x01, 0x01, 0x02, 0x0e, 0x00, 0x00,
};

int
main (void)
{
  hb_blob_t *blob = hb_blob_create ((const char *) font_data, sizeof (font_data),
                                    HB_MEMORY_MODE_READONLY, NULL, NULL);
  hb_face_t *face = hb_face_create (blob, 0);
  hb_blob_destroy (blob);

  hb_font_t *font = hb_font_create (face);
  hb_ot_font_set_funcs (font);

  hb_subset_input_t *input = hb_subset_input_create_or_fail ();
  if (!input)
    return 1;
  hb_set_add (hb_subset_input_glyph_set (input), 0);

  hb_face_t *out = hb_subset_or_fail (face, input);
  hb_subset_input_destroy (input);
  if (out)
    hb_face_destroy (out);
  hb_font_destroy (font);
  hb_face_destroy (face);
  return 0;
}
