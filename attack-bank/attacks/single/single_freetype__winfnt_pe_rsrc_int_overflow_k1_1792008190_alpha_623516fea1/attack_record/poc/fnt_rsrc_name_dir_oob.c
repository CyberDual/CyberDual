int
main( void )
{
  FT_Library  library;
  FT_Face     face = NULL;
  FT_Byte*    data;
  FT_Error    error;


  /* pass the font as a memory-based stream, the way font data is */
  /* usually handed to FreeType by embedding applications         */
  data = (FT_Byte*)malloc( sizeof( font_data ) );
  if ( !data )
    return 1;

  memcpy( data, font_data, sizeof( font_data ) );

  if ( FT_Init_FreeType( &library ) )
    return 2;

  error = FT_New_Memory_Face( library,
                              data,
                              (FT_Long)sizeof( font_data ),
                              0,
                              &face );
  printf( "FT_New_Memory_Face error: %d\n", (int)error );

  if ( !error )
    FT_Done_Face( face );

  FT_Done_FreeType( library );

  free( data );

  return 0;
}
