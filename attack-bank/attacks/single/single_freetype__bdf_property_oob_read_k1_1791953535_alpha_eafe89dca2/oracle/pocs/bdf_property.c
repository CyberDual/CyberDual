  int
  main( void )
  {
    const char*        font_path = "/tmp/freetype-bdf-property.ttf";
    FILE*              file;
    FT_Library         library;
    FT_Face            face;
    BDF_PropertyRec    property;
    FT_Error           error;


    file = fopen( font_path, "wb" );
    if ( !file )
      return 1;

    if ( fwrite( font_data, 1, sizeof ( font_data ), file ) !=
         sizeof ( font_data ) )
    {
      fclose( file );
      return 2;
    }

    fclose( file );

    error = FT_Init_FreeType( &library );
    if ( error )
      return 3;

    error = FT_New_Face( library, font_path, 0, &face );
    if ( error )
    {
      FT_Done_FreeType( library );
      return 4;
    }

    error = FT_Set_Pixel_Sizes( face, 0, 16 );
    if ( error )
    {
      FT_Done_Face( face );
      FT_Done_FreeType( library );
      return 5;
    }

    error = FT_Get_BDF_Property( face, "NAME", &property );
    printf( "property error: %d\n", error );

    FT_Done_Face( face );
    FT_Done_FreeType( library );
    remove( font_path );

    return error == 0 ? 0 : 6;
  }
