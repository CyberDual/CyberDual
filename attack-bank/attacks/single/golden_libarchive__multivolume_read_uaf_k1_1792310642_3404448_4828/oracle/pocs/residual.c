static char *
write_volume(const char *dir, const char *name,
    const unsigned char *data, size_t size)
{
	char *path;
	FILE *fp;

	path = malloc(strlen(dir) + strlen(name) + 2);
	if (path == NULL)
		return (NULL);
	sprintf(path, "%s/%s", dir, name);
	fp = fopen(path, "wb");
	if (fp == NULL) {
		free(path);
		return (NULL);
	}
	fwrite(data, 1, size, fp);
	fclose(fp);
	return (path);
}

int
main(void)
{
	const char *filenames[3];
	char *f1, *f2;
	struct archive *a;
	struct archive_entry *ae;
	int r;

	f1 = write_volume(".", "split_vol1.tar", volume1, sizeof(volume1));
	f2 = write_volume(".", "split_vol2.tar", volume2, sizeof(volume2));
	if (f1 == NULL || f2 == NULL) {
		fprintf(stderr, "cannot write volume files\n");
		return (2);
	}
	filenames[0] = f1;
	filenames[1] = f2;
	filenames[2] = NULL;

	a = archive_read_new();
	archive_read_support_filter_uu(a);
	archive_read_support_format_tar(a);

	r = archive_read_open_filenames(a, filenames, 4096);
	if (r != ARCHIVE_OK) {
		fprintf(stderr, "open failed: %s\n", archive_error_string(a));
		return (1);
	}

	r = archive_read_next_header(a, &ae);
	printf("first header: %d (%s)\n", r,
	    r == ARCHIVE_OK ? archive_entry_pathname(ae) : "-");

	r = archive_read_next_header(a, &ae);
	printf("second header: %d\n", r);

	archive_read_free(a);
	remove(f1);
	remove(f2);
	free(f1);
	free(f2);
	return (0);
}
