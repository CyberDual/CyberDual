static int
write_input (const char* path)
{
    FILE* file = fopen (path, "wb");
    if (!file) return 0;

    size_t written = fwrite (input, 1, sizeof (input), file);
    fclose (file);
    return written == sizeof (input);
}

int
main (int argc, char* argv[])
{
    const char* path =
        argc == 2 ? argv[1] : "/tmp/openexr-newbug.exr";
    exr_context_t             file = NULL;
    exr_context_initializer_t initializer = EXR_DEFAULT_CONTEXT_INITIALIZER;
    exr_attr_box2i_t          data_window;
    exr_chunk_info_t          chunk;
    exr_decode_pipeline_t     decoder = EXR_DECODE_PIPELINE_INITIALIZER;
    exr_result_t              result;
    int                       decoder_ready = 0;

    if (!write_input (path)) return 2;

    result = exr_start_read (&file, path, &initializer);
    if (result != EXR_ERR_SUCCESS) return 1;

    result = exr_get_data_window (file, 0, &data_window);
    if (result == EXR_ERR_SUCCESS)
        result = exr_read_scanline_chunk_info (
            file, 0, data_window.min.y, &chunk);

    if (result == EXR_ERR_SUCCESS)
    {
        result = exr_decoding_initialize (file, 0, &chunk, &decoder);
        decoder_ready = (result == EXR_ERR_SUCCESS);
    }
    if (result == EXR_ERR_SUCCESS)
    {
        decoder.decode_flags |= EXR_DECODE_SAMPLE_COUNTS_AS_INDIVIDUAL;
        result = exr_decoding_choose_default_routines (file, 0, &decoder);
    }
    if (result == EXR_ERR_SUCCESS)
        result = exr_decoding_run (file, 0, &decoder);

    if (decoder_ready) exr_decoding_destroy (file, &decoder);
    if (file != NULL) exr_finish (&file);

    return result == EXR_ERR_SUCCESS ? 0 : 1;
}
