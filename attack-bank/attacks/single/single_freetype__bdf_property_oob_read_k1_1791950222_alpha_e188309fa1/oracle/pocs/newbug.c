int
main( void )
{
  FT_Library       lib;
  FT_Face          face;
  BDF_PropertyRec  prop;
  unsigned char*   buf;
  FT_Error         err;

  buf = (unsigned char*)malloc( sizeof ( font_data ) );
  if ( !buf )
    return 1;
  memcpy( buf, font_data, sizeof ( font_data ) );

  if ( FT_Init_FreeType( &lib ) )
    return 1;

  err = FT_New_Memory_Face( lib, buf, (FT_Long)sizeof ( font_data ), 0, &face );
  if ( err )
    return 2;

  err = FT_Set_Pixel_Sizes( face, 16, 16 );
  if ( err )
    return 3;

  err = FT_Get_BDF_Property( face, "FOO", &prop );

  FT_Done_Face( face );
  FT_Done_FreeType( lib );
  free( buf );

  return err ? 1 : 0;
}
