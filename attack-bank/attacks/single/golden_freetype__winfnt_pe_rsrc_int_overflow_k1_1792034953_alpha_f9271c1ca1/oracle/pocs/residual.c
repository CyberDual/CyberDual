int
main(void)
{
  const char*  path = "/tmp/winfnt-rsrc.fon";
  FILE*        f;
  FT_Library   library;
  FT_Face      face;

  f = fopen(path, "wb");
  if (!f)
    return 1;
  if (fwrite(font_data, 1, sizeof(font_data), f) != sizeof(font_data))
    return 1;
  fclose(f);

  if (FT_Init_FreeType(&library))
    return 1;
  FT_New_Face(library, path, 0, &face);
  FT_Done_FreeType(library);
  return 0;
}
