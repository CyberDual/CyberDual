int
main(void)
{
	struct archive *a;
	struct archive_entry *ae;
	char buf[8192];
	ssize_t n;
	int r;

	a = archive_read_new();
	if (a == NULL)
		return (1);
	archive_read_support_filter_all(a);
	archive_read_support_format_7zip(a);
	r = archive_read_open_memory(a, archive_bytes, sizeof(archive_bytes));
	if (r != ARCHIVE_OK) {
		fprintf(stderr, "%s\n", archive_error_string(a));
		archive_read_free(a);
		return (1);
	}
	r = archive_read_next_header(a, &ae);
	if (r != ARCHIVE_OK) {
		fprintf(stderr, "%s\n", archive_error_string(a));
		archive_read_free(a);
		return (1);
	}
	while ((n = archive_read_data(a, buf, sizeof(buf))) > 0)
		;
	if (n < 0)
		fprintf(stderr, "%s\n", archive_error_string(a));
	archive_read_free(a);
	return (n < 0 ? 1 : 0);
}
