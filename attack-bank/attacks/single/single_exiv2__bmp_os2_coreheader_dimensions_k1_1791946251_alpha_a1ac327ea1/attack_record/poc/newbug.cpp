//
// Build against an ASan build of exiv2:
//   g++ -std=c++17 -g -fsanitize=address -I<exiv2>/include -I<build> \
//       pocs/newbug.cpp -L<build>/lib -lexiv2 -o newbug
// Run:
//   LD_LIBRARY_PATH=<build>/lib ASAN_OPTIONS=abort_on_error=1 ./newbug [file.bmp]
