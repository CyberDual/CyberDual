/* deliver the font through a caller-provided stream so that frame    */
/* accesses go through FT_Stream_Read into freshly allocated buffers  */
static unsigned long
font_stream_read( FT_Stream      stream,
                  unsigned long  offset,
                  unsigned char* buffer,
                  unsigned long  count )
{
  if ( offset >= sizeof ( font_data ) )
    return 0;

  if ( count > sizeof ( font_data ) - offset )
    count = sizeof ( font_data ) - offset;

  if ( count > 0 )
    memcpy( buffer, font_data + offset, count );

  (void)stream;
  return count;
}


static void
font_stream_close( FT_Stream  stream )
{
  (void)stream;
}


int
main( void )
{
  FT_StreamRec   stream;
  FT_Open_Args   args;
  FT_Library     library;
  FT_Face        face;
  FT_Vector      kern;
  FT_Error       error;


  error = FT_Init_FreeType( &library );
  if ( error )
    return 1;

  memset( &stream, 0, sizeof ( stream ) );
  stream.size  = sizeof ( font_data );
  stream.read  = font_stream_read;
  stream.close = font_stream_close;

  memset( &args, 0, sizeof ( args ) );
  args.flags  = FT_OPEN_STREAM;
  args.stream = &stream;

  error = FT_Open_Face( library, &args, 0, &face );
  if ( error )
  {
    fprintf( stderr, "FT_Open_Face failed: 0x%x\n", error );
    return 1;
  }

  if ( !FT_HAS_KERNING( face ) )
  {
    fprintf( stderr, "face has no kerning\n" );
    return 1;
  }

  kern.x = kern.y = -1;
  error  = FT_Get_Kerning( face, 1, 1, FT_KERNING_UNSCALED, &kern );

  printf( "kern: (%ld, %ld), error 0x%x\n",
          (long)kern.x, (long)kern.y, error );

  FT_Done_Face( face );
  FT_Done_FreeType( library );

  return 0;
}
