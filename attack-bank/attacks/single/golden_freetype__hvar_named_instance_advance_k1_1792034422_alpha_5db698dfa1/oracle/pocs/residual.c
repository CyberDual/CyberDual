static const unsigned int font_size = 544;


int
main( void )
{
  FT_Library  library;
  FT_Face     face;
  FT_Fixed    advance;
  FT_Error    error;


  error = FT_Init_FreeType( &library );
  if ( error )
    return 1;

  error = FT_New_Memory_Face( library, font_data, font_size, 0, &face );
  if ( error )
  {
    fprintf( stderr, "FT_New_Memory_Face failed: 0x%02x\n", error );
    return 2;
  }

  error = FT_Set_Named_Instance( face, 1 );
  if ( error )
  {
    fprintf( stderr, "FT_Set_Named_Instance failed: 0x%02x\n", error );
    return 3;
  }

  advance = 0;
  error = FT_Get_Advance( face, 0, FT_LOAD_NO_SCALE, &advance );
  fprintf( stderr, "glyph 0: error 0x%02x advance %ld\n",
           error, (long)advance );

  advance = 0;
  error = FT_Get_Advance( face, 1, FT_LOAD_NO_SCALE, &advance );
  fprintf( stderr, "glyph 1: error 0x%02x advance %ld\n",
           error, (long)advance );

  FT_Done_Face( face );
  FT_Done_FreeType( library );
  return error ? 4 : 0;
}
