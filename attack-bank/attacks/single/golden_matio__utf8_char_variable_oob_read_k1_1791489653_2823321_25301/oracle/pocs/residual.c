int
main(void)
{
    const char *path = "/tmp/residual_utf8.mat";
    FILE *f = fopen(path, "wb");
    matvar_t *matvar;
    mat_t *mat;

    if ( f == NULL )
        return 2;
    fwrite(crafted, 1, sizeof(crafted), f);
    fclose(f);

    mat = Mat_Open(path, MAT_ACC_RDONLY);
    if ( mat == NULL )
        return 2;

    while ( (matvar = Mat_VarReadNext(mat)) != NULL ) {
        if ( matvar->class_type == MAT_C_CHAR && matvar->data_type == MAT_T_UTF8 &&
             matvar->data != NULL ) {
            matvar_t *copy = Mat_VarCreate(matvar->name, MAT_C_CHAR, MAT_T_UTF8, matvar->rank,
                                           matvar->dims, matvar->data, 0);
            if ( copy != NULL )
                Mat_VarFree(copy);
        }
        Mat_VarFree(matvar);
    }

    Mat_Close(mat);
    return 0;
}
