struct reader {
	const unsigned char *next;
	size_t left;
	unsigned char *buf;
};

static la_ssize_t
read_cb(struct archive *a, void *client, const void **buffer)
{
	struct reader *r = client;
	size_t n;

	(void)a;
	free(r->buf);
	r->buf = malloc(BLOCK);
	if (r->buf == NULL)
		return (-1);
	n = r->left < BLOCK ? r->left : BLOCK;
	if (n)
		memcpy(r->buf, r->next, n);
	r->next += n;
	r->left -= n;
	*buffer = r->buf;
	return (la_ssize_t)n;
}

int
main(void)
{
	struct reader r;
	struct archive_entry *entry;
	struct archive *a;
	char data[BLOCK];
	la_ssize_t n, total = 0;
	int rc;

	r.next = archive_bytes;
	r.left = sizeof(archive_bytes);
	r.buf = NULL;

	a = archive_read_new();
	if (a == NULL) {
		fprintf(stderr, "archive_read_new failed\n");
		return (1);
	}
	if (archive_read_support_format_tar(a) != ARCHIVE_OK ||
	    archive_read_open(a, &r, NULL, read_cb, NULL) != ARCHIVE_OK) {
		fprintf(stderr, "setup failed: %s\n", archive_error_string(a));
		archive_read_free(a);
		return (1);
	}

	rc = archive_read_next_header(a, &entry);
	printf("next_header -> %d: %s size=%lld uid=%lld gid=%lld\n", rc,
	    rc == ARCHIVE_OK ? archive_entry_pathname(entry) : "(none)",
	    (long long)archive_entry_size(entry),
	    (long long)archive_entry_uid(entry),
	    (long long)archive_entry_gid(entry));
	if (rc != ARCHIVE_OK) {
		fprintf(stderr, "error: %s\n", archive_error_string(a));
		archive_read_free(a);
		free(r.buf);
		return (1);
	}

	while ((n = archive_read_data(a, data, sizeof(data))) > 0)
		total += n;
	printf("data bytes read: %lld\n", (long long)total);

	rc = archive_read_next_header(a, &entry);
	printf("next header -> %d (1 = EOF, ok)\n", rc);

	archive_read_close(a);
	archive_read_free(a);
	free(r.buf);
	return (0);
}
