static int
sampled_height (int height, int ys, int start_y)
{
    if (ys <= 1) return height;
    if (height == 1) return (start_y % ys) == 0 ? 1 : 0;
    int off = start_y < 0 ? (-start_y % ys)
                          : (start_y % ys ? ys - start_y % ys : 0);
    int t = height - off;
    if (t == 0) return 0;
    --t;
    return t / ys + 1;
}

int
main ()
{
    std::string path = "newbug_input.exr";
    {
        FILE* f = fopen (path.c_str(), "wb");
        if (!f) return 2;
        fwrite (kExrBytes, 1, sizeof (kExrBytes), f);
        fclose (f);
    }

    try
    {
        InputFile file (path.c_str());
        const Header& hdr = file.header ();
        Box2i         dw  = hdr.dataWindow ();
        int           W   = dw.max.x - dw.min.x + 1;
        int           H   = dw.max.y - dw.min.y + 1;

        FrameBuffer fb;
        std::vector<std::vector<char>> bufs;
        bufs.reserve (8);
        for (ChannelList::ConstIterator it = hdr.channels ().begin ();
             it != hdr.channels ().end (); ++it)
        {
            int bpe = it.channel ().type == HALF ? 2 : 4;
            int xs  = it.channel ().xSampling;
            int ys  = it.channel ().ySampling;
            int sw  = W > 1 ? W / xs : 1;
            int sh  = sampled_height (H, ys, dw.min.y);
            bufs.push_back (std::vector<char> ((size_t) sw * sh * bpe + 16, 0));
            fb.insert (it.name (),
                       Slice (it.channel ().type, bufs.back ().data (),
                              bpe, (size_t) bpe * sw, xs, ys, 0.0));
        }
        file.setFrameBuffer (fb);
        file.readPixels (dw.min.y, dw.max.y);
        printf ("decoded %dx%d without error\n", W, H);
    }
    catch (const std::exception& e)
    {
        printf ("read failed cleanly: %s\n", e.what ());
        return 1;
    }
    return 0;
}
