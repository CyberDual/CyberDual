static const size_t vol2_len = 980;

static int
write_tmp(const char *path, const unsigned char *data, size_t len)
{
	FILE *f = fopen(path, "wb");
	if (f == NULL)
		return (-1);
	if (fwrite(data, 1, len, f) != len) {
		fclose(f);
		return (-1);
	}
	fclose(f);
	return (0);
}

int
main(void)
{
	const char *path1 = "/tmp/residual_vol1.tar";
	const char *path2 = "/tmp/residual_vol2.tar";
	const char *filenames[3];
	struct archive *a;
	struct archive_entry *ae;
	int r;

	if (write_tmp(path1, vol1, vol1_len) != 0)
		return (1);
	if (write_tmp(path2, vol2, vol2_len) != 0)
		return (1);

	filenames[0] = path1;
	filenames[1] = path2;
	filenames[2] = NULL;

	a = archive_read_new();
	archive_read_support_filter_all(a);
	archive_read_support_format_tar(a);

	r = archive_read_open_filenames(a, filenames, 4096);
	if (r != ARCHIVE_OK) {
		fprintf(stderr, "open failed: %d\n", r);
		archive_read_free(a);
		return (1);
	}

	r = archive_read_next_header(a, &ae);
	fprintf(stderr, "header1: %d\n", r);

	r = archive_read_next_header(a, &ae);
	fprintf(stderr, "header2: %d\n", r);

	archive_read_free(a);
	return (0);
}
