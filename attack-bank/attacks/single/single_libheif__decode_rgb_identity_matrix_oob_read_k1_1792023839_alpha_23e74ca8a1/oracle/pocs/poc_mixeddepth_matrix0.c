int main(int argc, char** argv)
{
  (void) argc;
  (void) argv;

  const unsigned char* data = heif_file_mixed_depth;
  size_t size = sizeof(heif_file_mixed_depth);

  int rc = 1;

  heif_init(NULL);

  heif_context* ctx = heif_context_alloc();
  heif_image_handle* handle = NULL;
  heif_decoding_options* options = NULL;
  heif_image* img = NULL;

  do {
    heif_error err = heif_context_read_from_memory(ctx, data, size, NULL);
    if (err.code != heif_error_Ok) {
      fprintf(stderr, "read: %s\n", err.message);
      break;
    }

    err = heif_context_get_primary_image_handle(ctx, &handle);
    if (err.code != heif_error_Ok) {
      fprintf(stderr, "handle: %s\n", err.message);
      break;
    }

    options = heif_decoding_options_alloc();

    // Ask for the identity matrix / full range so the decoder converts the
    // planar RGB image to YCbCr with matrix_coefficients == 0.
    heif_color_profile_nclx nclx;
    memset(&nclx, 0, sizeof(nclx));
    nclx.version = 1;
    nclx.color_primaries = heif_color_primaries_ITU_R_BT_709_5;
    nclx.transfer_characteristics = heif_transfer_characteristic_ITU_R_BT_709_5;
    nclx.matrix_coefficients = heif_matrix_coefficients_RGB_GBR;
    nclx.full_range_flag = 1;
    options->output_image_nclx_profile = &nclx;

    err = heif_decode_image(handle, &img,
                            heif_colorspace_YCbCr, heif_chroma_420,
                            options);
    if (err.code != heif_error_Ok) {
      fprintf(stderr, "decode: %s\n", err.message);
      break;
    }

    printf("decoded %dx%d, colorspace %d, chroma %d\n",
           heif_image_get_width(img, heif_channel_Y),
           heif_image_get_height(img, heif_channel_Y),
           (int) heif_image_get_colorspace(img),
           (int) heif_image_get_chroma_format(img));

    rc = 0;
  } while (0);

  heif_image_release(img);
  heif_decoding_options_free(options);
  heif_image_handle_release(handle);
  heif_context_free(ctx);
  heif_deinit();

  return rc;
}
