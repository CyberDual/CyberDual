static int
b64_index(char c)
{
    if ( c >= 'A' && c <= 'Z' )
        return c - 'A';
    if ( c >= 'a' && c <= 'z' )
        return c - 'a' + 26;
    if ( c >= '0' && c <= '9' )
        return c - '0' + 52;
    if ( c == '+' )
        return 62;
    if ( c == '/' )
        return 63;
    return -1;
}

static unsigned char *
b64_decode(const char *src, size_t *out_len)
{
    size_t len = strlen(src);
    size_t groups = len / 4;
    size_t i, o = 0;
    unsigned char *out;

    if ( 0 != len % 4 )
        return NULL;
    out = (unsigned char *)malloc(groups * 3 + 1);
    if ( NULL == out )
        return NULL;

    for ( i = 0; i < groups; i++ ) {
        int v[4];
        int j;
        int pad = 0;
        for ( j = 0; j < 4; j++ ) {
            char c = src[4 * i + j];
            if ( c == '=' ) {
                v[j] = 0;
                pad++;
            } else {
                v[j] = b64_index(c);
                if ( v[j] < 0 ) {
                    free(out);
                    return NULL;
                }
            }
        }
        if ( pad > 2 ) {
            free(out);
            return NULL;
        }
        out[o++] = (unsigned char)((v[0] << 2) | (v[1] >> 4));
        out[o++] = (unsigned char)((v[1] << 4) | (v[2] >> 2));
        out[o++] = (unsigned char)((v[2] << 6) | v[3]);
        if ( pad > 0 ) {
            o -= (size_t)(pad - 1);
            break;
        }
    }
    *out_len = o;
    return out;
}

int
main(void)
{
    unsigned char *blob;
    size_t blob_len = 0;
    char tmpl[] = "pocXXXXXX";
    int fd;
    FILE *fp;
    mat_t *mat;
    matvar_t *st;
    char *const *fieldnames;
    unsigned nfields, k;

    blob = b64_decode(fixture_base64, &blob_len);
    if ( NULL == blob ) {
        fprintf(stderr, "failed to decode embedded fixture\n");
        return 1;
    }

    fd = mkstemp(tmpl);
    if ( fd < 0 ) {
        perror("mkstemp");
        free(blob);
        return 1;
    }
    fp = fdopen(fd, "wb");
    if ( NULL == fp ) {
        close(fd);
        free(blob);
        return 1;
    }
    if ( fwrite(blob, 1, blob_len, fp) != blob_len ) {
        fclose(fp);
        free(blob);
        return 1;
    }
    fclose(fp);
    free(blob);
    printf("fixture: %s\n", tmpl);

    mat = Mat_Open(tmpl, MAT_ACC_RDONLY);
    if ( NULL == mat ) {
        fprintf(stderr, "Mat_Open failed\n");
        unlink(tmpl);
        return 1;
    }

    st = Mat_VarRead(mat, "s");
    if ( NULL == st ) {
        fprintf(stderr, "Mat_VarRead failed\n");
        Mat_Close(mat);
        unlink(tmpl);
        return 1;
    }

    printf("class=%d rank=%d\n", (int)st->class_type, st->rank);
    fieldnames = Mat_VarGetStructFieldnames(st);
    nfields = Mat_VarGetNumberOfFields(st);
    printf("nfields=%u\n", nfields);
    for ( k = 0; NULL != fieldnames && k < nfields; k++ ) {
        matvar_t *field = Mat_VarGetStructFieldByName(st, fieldnames[k], 0);
        printf("field[%u]=%s\n", k, fieldnames[k]);
        if ( NULL != field && MAT_C_DOUBLE == field->class_type && NULL != field->data ) {
            printf("value=%g\n", ((double *)field->data)[0]);
        }
    }

    Mat_VarFree(st);
    Mat_Close(mat);
    unlink(tmpl);
    printf("no crash\n");
    return 0;
}
