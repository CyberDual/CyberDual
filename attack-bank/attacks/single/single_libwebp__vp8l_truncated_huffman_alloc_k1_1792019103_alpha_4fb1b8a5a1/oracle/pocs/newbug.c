#include <stdint.h>

#include "webp/decode.h"

static const uint8_t kWebPData[] = {
    0x52, 0x49, 0x46, 0x46, 0x12, 0x00, 0x00, 0x00, 0x57, 0x45, 0x42, 0x50,
    0x56, 0x50, 0x38, 0x4c, 0x06, 0x00, 0x00, 0x00, 0x2f, 0x00, 0x00, 0x00,
    0x00, 0x00};

int main(void) {
  WebPDecoderConfig config;
  if (!WebPInitDecoderConfig(&config)) return 1;
  (void)WebPDecode(kWebPData, sizeof(kWebPData), &config);
  WebPFreeDecBuffer(&config.output);
  return 0;
}
