int
main(void)
{
    char path[] = "/tmp/matio-utf8-XXXXXX";
    int fd;
    mat_t *mat;
    matvar_t *matvar;

    fd = mkstemp(path);
    if ( fd < 0 )
        return 1;
    if ( write(fd, kMat, sizeof(kMat)) != (ssize_t)sizeof(kMat) )
        return 1;
    if ( close(fd) != 0 )
        return 1;

    mat = Mat_Open(path, MAT_ACC_RDONLY);
    if ( mat == NULL ) {
        unlink(path);
        return 1;
    }
    while ( (matvar = Mat_VarReadNext(mat)) != NULL )
        Mat_VarFree(matvar);
    Mat_Close(mat);
    unlink(path);
    return 0;
}
