int
main(void)
{
	struct archive *a;
	struct archive_entry *ae;
	char buf[100];
	int r;

	a = archive_read_new();
	if (a == NULL)
		return (1);
	archive_read_support_filter_none(a);
	archive_read_support_format_7zip(a);
	if (archive_read_open_memory(a, archive_bytes,
	    sizeof(archive_bytes)) != ARCHIVE_OK) {
		fprintf(stderr, "open: %s\n", archive_error_string(a));
		archive_read_free(a);
		return (1);
	}
	r = archive_read_next_header(a, &ae);
	if (r != ARCHIVE_OK) {
		fprintf(stderr, "header: %s\n", archive_error_string(a));
		archive_read_free(a);
		return (1);
	}
	r = (int)archive_read_data(a, buf, sizeof(buf));
	printf("data: %d (%s)\n", r, archive_error_string(a));
	archive_read_free(a);
	return (0);
}
