/*
 * ppmd_short_params.c
 *
 * Read a 7-Zip archive whose folder is coded with PPMd and carries a
 * truncated coder property record, through the public archive_read API.
 */
#include <stdio.h>
#include <stdlib.h>
#include <archive.h>
#include <archive_entry.h>

static const unsigned char archive_bytes[] = {
	0x37,0x7a,0xbc,0xaf,0x27,0x1c,0x00,0x04,0x9e,0xcf,0x82,0x6e,
	0x18,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x30,0x00,0x00,0x00,
	0x00,0x00,0x00,0x00,0xc4,0x35,0x61,0xa9,0xa5,0x4d,0xca,0x18,
	0x25,0x30,0xbb,0x1d,0x6d,0x13,0x2c,0xde,0xd6,0x23,0x7b,0x2e,
	0xd9,0x1e,0x3f,0x72,0x1f,0xcb,0x19,0x71,0x01,0x04,0x06,0x00,
	0x01,0x09,0x18,0x00,0x07,0x0b,0x01,0x00,0x01,0x23,0x03,0x04,
	0x01,0x04,0x06,0x00,0x00,0x00,0x0c,0x84,0x00,0x00,0x08,0x00,
	0x00,0x05,0x01,0x11,0x0d,0x00,0x61,0x00,0x2e,0x00,0x74,0x00,
	0x78,0x00,0x74,0x00,0x00,0x00,0x00,0x00,
};

int
main(void)
{
	struct archive *a;
	struct archive_entry *ae;
	const void *buff;
	size_t size;
	la_int64_t offset;
	int r;

	a = archive_read_new();
	if (a == NULL)
		return (2);
	archive_read_support_filter_all(a);
	archive_read_support_format_7zip(a);
	r = archive_read_open_memory(a, archive_bytes, sizeof(archive_bytes));
	if (r != ARCHIVE_OK) {
		fprintf(stderr, "open: %s\n", archive_error_string(a));
		archive_read_free(a);
		return (1);
	}
	while ((r = archive_read_next_header(a, &ae)) == ARCHIVE_OK) {
		fprintf(stderr, "entry: %s\n", archive_entry_pathname(ae));
		for (;;) {
			r = archive_read_data_block(a, &buff, &size, &offset);
			if (r == ARCHIVE_EOF)
				break;
			if (r < ARCHIVE_OK) {
				fprintf(stderr, "data: %s\n",
				    archive_error_string(a));
				break;
			}
		}
	}
	if (r != ARCHIVE_EOF)
		fprintf(stderr, "next_header: %s\n", archive_error_string(a));
	archive_read_free(a);
	return (0);
}
