int
main(int argc, char **argv)
{
    const char *path = argc > 1 ? argv[1] : "newbug.mat";
    FILE *f = fopen(path, "wb");
    mat_t *mat;
    matvar_t *matvar;

    if ( f == NULL )
        return EXIT_FAILURE;
    fwrite(mat_bytes, 1, sizeof(mat_bytes), f);
    fclose(f);

    mat = Mat_Open(path, MAT_ACC_RDONLY);
    if ( mat == NULL )
        return EXIT_FAILURE;

    while ( (matvar = Mat_VarReadNext(mat)) != NULL ) {
        Mat_VarFree(matvar);
    }

    Mat_Close(mat);
    return EXIT_SUCCESS;
}
