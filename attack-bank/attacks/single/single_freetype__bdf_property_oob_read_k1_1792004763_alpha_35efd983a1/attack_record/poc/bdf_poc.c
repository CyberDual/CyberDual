#define FONT_PATH  "/tmp/ft_bdf_poc_input.ttf"


static void
write_font( void )
{
  FILE*  f = fopen( FONT_PATH, "wb" );


  if ( !f )
  {
    fprintf( stderr, "cannot write %s\n", FONT_PATH );
    exit( 1 );
  }

  if ( fwrite( font_data, 1, sizeof ( font_data ), f )
         != sizeof ( font_data ) )
  {
    fprintf( stderr, "short write\n" );
    fclose( f );
    exit( 1 );
  }

  fclose( f );
}


int
main( void )
{
  FT_Library       library;
  FT_Face          face;
  BDF_PropertyRec  prop;
  FT_Error         error;


  write_font();

  error = FT_Init_FreeType( &library );
  if ( error )
  {
    printf( "FT_Init_FreeType failed: %d\n", error );
    return 1;
  }

  error = FT_New_Face( library, FONT_PATH, 0, &face );
  if ( error )
  {
    printf( "FT_New_Face failed: %d\n", error );
    FT_Done_FreeType( library );
    return 1;
  }
  printf( "face loaded, %ld glyphs\n", (long)face->num_glyphs );

  error = FT_Set_Char_Size( face, 16 * 64, 16 * 64, 72, 72 );
  if ( error )
    printf( "FT_Set_Char_Size: %d\n", error );

  error = FT_Get_BDF_Property( face, "FOUNDRY", &prop );
  printf( "FT_Get_BDF_Property: %d\n", error );
  if ( !error && prop.type == BDF_PROPERTY_TYPE_ATOM )
    printf( "  atom: %s\n", prop.u.atom );

  FT_Done_Face( face );
  FT_Done_FreeType( library );
  printf( "done\n" );

  return 0;
}
