#include <ft2build.h>
#include FT_FREETYPE_H

#include <stdio.h>
#include <string.h>


/* Minimal PFR: three sorted 2-byte kerning pairs, 1-byte adjustments.
   Glyphs 1 and 2 are character codes 1 and 3, so the looked-up pair is
   the last record.  The pair count is not a power of two. */
static const unsigned char  font_data[] =
{
  0x50, 0x46, 0x52, 0x30, 0x00, 0x00, 0x0d, 0x0a, 0x00, 0x3a, 0x00, 0x07, 0x00, 0x3a, 0x00, 0x12,
  0x00, 0x00, 0x12, 0x00, 0x00, 0x41, 0x00, 0x3b, 0x00, 0x00, 0x3b, 0x00, 0x00, 0x53, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x02, 0x00, 0x01, 0x00, 0x12, 0x00, 0x00,
  0x41, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x3b,
  0x00, 0x00, 0x53, 0x00, 0x00, 0x03, 0xe8, 0x03, 0xe8, 0x00, 0x00, 0xff, 0x38, 0x01, 0xf4, 0x03,
  0x20, 0x80, 0x01, 0xf4, 0x01, 0x13, 0x04, 0x03, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x01, 0x00,
  0x00, 0x01, 0x00, 0x02, 0x00, 0x00, 0x01, 0x00, 0x03, 0x05, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x02, 0xbc, 0x01, 0xf4, 0x00, 0x02, 0x01, 0x00, 0x00, 0x01, 0x03, 0x00, 0x00, 0x00
};

static unsigned long
read_font( FT_Stream       stream,
           unsigned long   offset,
           unsigned char*  buffer,
           unsigned long   count )
{
  (void)stream;

  if ( count == 0 )
    return offset <= sizeof ( font_data ) ? 0 : 1;

  if ( offset >= sizeof ( font_data ) )
    return 0;

  if ( offset + count > sizeof ( font_data ) )
    count = sizeof ( font_data ) - offset;

  memcpy( buffer, font_data + offset, count );
  return count;
}


int
main( void )
{
  FT_Library    library;
  FT_Face       face;
  FT_StreamRec  stream;
  FT_Open_Args  args;
  FT_Vector     kerning;
  FT_Error      error;


  error = FT_Init_FreeType( &library );
  if ( error )
    return 1;

  memset( &stream, 0, sizeof ( stream ) );
  stream.size = sizeof ( font_data );
  stream.read = read_font;

  memset( &args, 0, sizeof ( args ) );
  args.flags  = FT_OPEN_STREAM;
  args.stream = &stream;

  error = FT_Open_Face( library, &args, 0, &face );
  if ( error )
  {
    fprintf( stderr, "FT_Open_Face failed: 0x%02x\n", error );
    FT_Done_FreeType( library );
    return 1;
  }

  /* Public kerning query.  Glyph indices skip .notdef, so 1 and 2 are
     the two encoded characters. */
  error = FT_Get_Kerning( face, 1, 2, FT_KERNING_UNSCALED, &kerning );
  if ( !error )
    printf( "kerning %ld\n", (long)kerning.x );

  FT_Done_Face( face );
  FT_Done_FreeType( library );
  return error ? 1 : 0;
}
