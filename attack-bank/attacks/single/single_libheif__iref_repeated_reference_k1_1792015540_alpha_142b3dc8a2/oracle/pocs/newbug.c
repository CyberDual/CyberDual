int main(void)
{
  const char* path = "/tmp/libheif_iovl_split_dimg.heif";

  FILE* f = fopen(path, "wb");
  if (!f) {
    perror("fopen");
    return 1;
  }
  if (fwrite(file_bytes, 1, sizeof(file_bytes), f) != sizeof(file_bytes)) {
    fclose(f);
    return 1;
  }
  fclose(f);

  heif_context* ctx = heif_context_alloc();
  if (!ctx) {
    return 1;
  }

  heif_error err = heif_context_read_from_file(ctx, path, NULL);
  if (err.code != heif_error_Ok) {
    printf("read failed: %s\n", err.message);
    heif_context_free(ctx);
    return 0;
  }

  heif_image_handle* handle = NULL;
  err = heif_context_get_primary_image_handle(ctx, &handle);
  if (err.code != heif_error_Ok) {
    printf("handle failed: %s\n", err.message);
    heif_context_free(ctx);
    return 0;
  }

  heif_image* img = NULL;
  err = heif_decode_image(handle, &img, heif_colorspace_undefined,
                          heif_chroma_undefined, NULL);
  printf("decode: %s\n", err.message);

  if (img) {
    heif_image_release(img);
  }
  heif_image_handle_release(handle);
  heif_context_free(ctx);
  return 0;
}
