#include <exiv2/basicio.hpp>
#include <exiv2/bmpimage.hpp>

#include <array>

int main() {
  const std::array<Exiv2::byte, 34> bmp{
      'B',  'M', 0x22, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x1e, 0x00,
      0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x00,
      0x00, 0x00, 0x01, 0x00, 0x18, 0x00, 0x00, 0x00, 0x00, 0x00,
  };
  auto io = std::make_unique<Exiv2::MemIo>(bmp.data(), bmp.size());
  Exiv2::BmpImage image(std::move(io), Exiv2::ImageCtorParams(false, 1000));
  image.readMetadata();
  return image.pixelWidth() == 1 && image.pixelHeight() == 1 ? 0 : 1;
}
