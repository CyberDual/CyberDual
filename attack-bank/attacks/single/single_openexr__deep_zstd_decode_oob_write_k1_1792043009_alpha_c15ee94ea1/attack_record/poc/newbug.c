int
main (int argc, char** argv)
{
    char path[512];
    if (argc > 1) snprintf (path, sizeof (path), "%s", argv[1]);
    else snprintf (
        path, sizeof (path), "%s/openexr_deep_zstd_poc_tail.exr",
        getenv ("TMPDIR") ? getenv ("TMPDIR") : "/tmp");

    FILE* f = fopen (path, "wb");
    if (!f) { fprintf (stderr, "cannot write %s\n", path); return 1; }
    if (fwrite (deep_zstd_exr, 1, sizeof (deep_zstd_exr), f) !=
        sizeof (deep_zstd_exr))
    {
        fprintf (stderr, "short write\n");
        fclose (f);
        return 1;
    }
    fclose (f);

    exr_context_initializer_t cinit = EXR_DEFAULT_CONTEXT_INITIALIZER;
    exr_context_t         ctxt  = NULL;
    exr_chunk_info_t      cinfo;
    exr_decode_pipeline_t decoder;
    exr_attr_box2i_t      dw;
    exr_result_t          rv;

    rv = exr_start_read (&ctxt, path, &cinit);
    if (rv != EXR_ERR_SUCCESS)
    {
        fprintf (stderr, "exr_start_read failed: %d\n", (int) rv);
        return 1;
    }

    rv = exr_get_data_window (ctxt, 0, &dw);
    if (rv != EXR_ERR_SUCCESS) return 1;

    rv = exr_read_scanline_chunk_info (ctxt, 0, dw.min.y, &cinfo);
    if (rv != EXR_ERR_SUCCESS)
    {
        fprintf (stderr, "chunk info failed: %d\n", (int) rv);
        return 1;
    }

    decoder = (exr_decode_pipeline_t) EXR_DECODE_PIPELINE_INITIALIZER;
    rv      = exr_decoding_initialize (ctxt, 0, &cinfo, &decoder);
    if (rv != EXR_ERR_SUCCESS) return 1;
    rv = exr_decoding_choose_default_routines (ctxt, 0, &decoder);
    if (rv != EXR_ERR_SUCCESS) return 1;

    rv = exr_decoding_run (ctxt, 0, &decoder);
    if (rv != EXR_ERR_SUCCESS)
        printf ("chunk rejected by decoder (rv=%d)\n", (int) rv);
    else
        printf ("chunk decoded\n");

    exr_decoding_destroy (ctxt, &decoder);
    exr_finish (&ctxt);
    remove (path);
    return 0;
}
