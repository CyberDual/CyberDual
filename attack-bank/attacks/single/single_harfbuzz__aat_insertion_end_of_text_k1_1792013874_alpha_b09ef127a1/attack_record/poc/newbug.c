int main (void)
{
  unsigned int size = sizeof (font_data);

  /* Give the font its own heap allocation so that reads past the end of
   * the blob are caught by AddressSanitizer. */
  char *data = (char *) malloc (size);
  if (!data) return 1;
  memcpy (data, font_data, size);

  hb_blob_t *blob = hb_blob_create (data, (unsigned int) size,
				    HB_MEMORY_MODE_READONLY, data, free);
  hb_face_t *face = hb_face_create (blob, 0);
  hb_font_t *font = hb_font_create (face);

  hb_buffer_t *buffer = hb_buffer_create ();
  hb_buffer_add_utf8 (buffer, "AB", -1, 0, -1);
  hb_buffer_guess_segment_properties (buffer);

  hb_shape (font, buffer, NULL, 0);

  unsigned int len = hb_buffer_get_length (buffer);
  hb_glyph_info_t *info = hb_buffer_get_glyph_infos (buffer, NULL);
  printf ("output (%u):", len);
  for (unsigned int i = 0; i < len; i++)
    printf (" %u", info[i].codepoint);
  printf ("\n");

  hb_buffer_destroy (buffer);
  hb_font_destroy (font);
  hb_face_destroy (face);
  hb_blob_destroy (blob);
  return 0;
}
