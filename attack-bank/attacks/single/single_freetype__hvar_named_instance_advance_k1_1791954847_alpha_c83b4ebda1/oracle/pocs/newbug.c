int main( void )
{
  FT_Library  lib;
  FT_Face     face;
  FT_Fixed    advance = 0;
  FT_Error    error;
  FT_Byte*    data;


  error = FT_Init_FreeType( &lib );
  if ( error )
    return 1;

  /* exact-size heap copy: reads past the end are ASan-detectable */
  data = (FT_Byte*)malloc( FONT_LEN );
  if ( !data )
    return 1;
  memcpy( data, font_data, FONT_LEN );

  error = FT_New_Memory_Face( lib, data, FONT_LEN, 0, &face );
  if ( error )
  {
    printf( "FT_New_Memory_Face error 0x%x\n", error );
    return 1;
  }

  error = FT_Set_Named_Instance( face, 1 );
  if ( error )
  {
    printf( "FT_Set_Named_Instance error 0x%x\n", error );
    return 1;
  }

  error = FT_Get_Advance( face, 7, FT_LOAD_NO_SCALE, &advance );
  printf( "advance: error=%d value=%ld\n", error, (long)advance );

  FT_Done_Face( face );
  free( data );
  FT_Done_FreeType( lib );
  return 0;
}
